// Package account holds the model of the account of a book.
//
// An account is a bucket of money inside the book of a business: the cash
// the person has, the salary they earn, the food they eat, the money they
// owe to a friend.
//
// The five kinds of an account are the five of the accounting, and the kind
// says what the account means: an asset is what the person has, a liability
// is what the person owes, an income is what the person earns, an expense is
// what the person spends, and an equity is what the person put into the
// book of their own business.
//
// A debt is an account, and never a table of its own: a loan with a friend
// is a liability account with a counterparty and a due date, and the balance
// of that account is what the person still owes.
//
// The package imports nothing but the standard library, the model of the
// business that owns the book and the model of the person.
package account

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
)

// ID is the identity of an account.
//
// The number is generated by the database: it is a counter of the accounts
// and not a number of the person. The type exists so that an identifier
// never travels as a plain integer by accident.
type ID int64

// Kind is the kind of an account.
type Kind string

const (
	// KindAsset is the kind of what the person has: the cash, the bank.
	KindAsset Kind = "asset"

	// KindLiability is the kind of what the person owes: the loan of a
	// friend, the product that will be paid later.
	KindLiability Kind = "liability"

	// KindIncome is the kind of what the person earns.
	KindIncome Kind = "income"

	// KindExpense is the kind of what the person spends.
	KindExpense Kind = "expense"

	// KindEquity is the kind of what the person put into the book of their
	// own business.
	KindEquity Kind = "equity"
)

// kinds holds the kinds of an account, in the order they are presented.
var kinds = []Kind{
	KindAsset,
	KindLiability,
	KindIncome,
	KindExpense,
	KindEquity,
}

// AllKinds returns the kinds of an account.
//
// The caller receives a copy: the order and the content of the list never
// change under it.
func AllKinds() []Kind {
	all := make([]Kind, len(kinds))
	copy(all, kinds)
	return all
}

// Valid reports whether the kind is one of the kinds of an account.
func (k Kind) Valid() bool {
	for _, candidate := range kinds {
		if k == candidate {
			return true
		}
	}
	return false
}

// String returns the name of the kind.
//
// It is the name the storage holds, with no translation in between.
func (k Kind) String() string {
	return string(k)
}

// ParseKind returns the kind of the given name.
//
// The storage refuses a name that is not one of the kinds of an account, so a
// name that fails here would fail there too. The error wraps ErrUnknownKind,
// so a caller can tell an unknown kind from a failure of something else.
func ParseKind(name string) (Kind, error) {
	kind := Kind(name)
	if !kind.Valid() {
		return "", fmt.Errorf("%w: %q", ErrUnknownKind, name)
	}
	return kind, nil
}

// NormalSign returns the sign that turns the raw balance of an account into
// the balance the person reads.
//
// An asset and an expense count as they are: what the person has and what
// they spend are positive when they grow. A liability, an income and an
// equity count the other way round: what the person owes, what they earn
// and what they put into the book are positive when they grow, and the raw
// sum of their movements is negative.
//
// The sign belongs to the kind, because the kind is what says what the
// account means.
func (k Kind) NormalSign() int {
	switch k {
	case KindAsset, KindExpense:
		return 1
	case KindLiability, KindIncome, KindEquity:
		return -1
	}

	return 0
}

// CarriesDebt reports whether the kind is a kind that may owe or be owed.
//
// An account of money that is owed carries a counterparty and a due date. An
// account of an income or of an expense carries neither: nobody owes the
// salary of a person, and no expense falls due to somebody.
func (k Kind) CarriesDebt() bool {
	return k == KindLiability || k == KindAsset
}

// Account is an account of the book of a business.
type Account struct {
	// ID is the identity of the account. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the identity of the business that owns the account.
	BusinessID business.ID

	// Kind is the kind of the account.
	Kind Kind

	// Name is the name the person reads in their book. It is unique inside
	// the business that owns the account.
	Name string

	// Counterparty is the other side of a debt: the friend who lends the
	// money, the supplier the person owes. Empty means the account carries
	// no counterparty, and the storage writes NULL.
	Counterparty string

	// DueDate is the day a debt falls due. Nil means the account carries no
	// due date, and the storage writes NULL.
	DueDate *time.Time

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage filled
	// it on insert; whoever updates a row is responsible for it after that.
	UpdatedAt time.Time
}

// IsDebt reports whether the account carries a debt.
//
// The account carries a debt when its kind says that it owes or that it is
// owed, and when it names the other side of the money. The counterparty is
// what turns a balance into a debt: without it the account is a bucket of
// money and nobody waits for its payment.
func (a Account) IsDebt() bool {
	return a.Kind.CarriesDebt() && strings.TrimSpace(a.Counterparty) != ""
}

// New builds an account of the domain.
//
// The name loses the spaces around it, and it may not be empty: an account
// without a name has nothing to show in the book of the person. The name of
// an account is unique inside the business that owns it, and the storage
// holds the same rule as a defense in depth.
//
// The counterparty and the due date belong to a debt, and a debt is an
// account that owes or is owed. An account of any other kind carries
// neither, and the domain refuses the pair that breaks the rule.
//
// The identity of the account is not set here: the storage generates it,
// because the number is a counter of the accounts and not a number of the
// person.
func New(businessID business.ID, kind Kind, name, counterparty string, dueDate *time.Time) (Account, error) {
	if !kind.Valid() {
		return Account{}, fmt.Errorf("%w: %q", ErrUnknownKind, kind)
	}

	trimmedName := strings.TrimSpace(name)
	if trimmedName == "" {
		return Account{}, fmt.Errorf("%w: the name of an account is not empty", ErrInvalidName)
	}

	trimmedCounterparty := strings.TrimSpace(counterparty)
	if trimmedCounterparty != "" && !kind.CarriesDebt() {
		return Account{}, fmt.Errorf("%w: an account of the kind %q carries no counterparty", ErrDebtNotAllowed, kind)
	}

	if dueDate != nil && !kind.CarriesDebt() {
		return Account{}, fmt.Errorf("%w: an account of the kind %q carries no due date", ErrDebtNotAllowed, kind)
	}

	return Account{
		BusinessID:   businessID,
		Kind:         kind,
		Name:         trimmedName,
		Counterparty: trimmedCounterparty,
		DueDate:      dueDate,
	}, nil
}
