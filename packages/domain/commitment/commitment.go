// Package commitment holds the model of the commitment of the bakery: the
// promise of what is due and the day it is due.
//
// A commitment is a PROMISE of the business: what is due, in the words of
// the owner, and the day it is due. It is not a sale and it is not an order:
// the order of the bakery already owns the client delivery — the party, the
// products, the money and the round — and the commitment never copies it.
// The promise carries NO money and NO party: the "what" is the promise in
// the words of the owner, and it may name the party in her own words.
//
// The commitment that was met is KEPT, with the day it was met: the promise
// that was kept is a fact of the book, and the book never hides the day it
// was kept. There is no state column anywhere in the model: the day of
// meeting IS the fact, and a state column would be a second truth for it.
//
// The ALARM is the work of the agent. PACA holds the fact of what is due and
// the day it is due, and the agent is the one that rings: the calendar of a
// day is what the agent reads to know what is due and what is still owed.
//
// The package imports nothing but the standard library and the models it
// needs: the business that owns the promise and the day of the book.
package commitment

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ledger"
)

// ID is the identity of a commitment.
//
// The number is generated by the database: it is the counter of the
// commitments and not a number of the party. The type exists so that an
// identifier never travels as a plain integer by accident.
//
// The identity of a commitment is its OWN identity, never its text: two
// promises that say the same thing on the same day are two promises, and the
// book never merges them.
type ID int64

// Commitment is the promise of the business: what is due, in the words of
// the owner, and the day it is due.
//
// The commitment that was met carries the day it was met, and it is kept:
// the promise that was kept is a fact of the book. The commitment that was
// not met carries no day of meeting, and it is still owed.
type Commitment struct {
	// ID is the identity of the commitment. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that owes the promise.
	BusinessID business.ID

	// What is what is due, in the words of the owner. It is never empty,
	// and it carries no space around it.
	//
	// The promise names no party and no product of its own: whether it
	// names them is the wording of the owner, and the book never copies
	// the party or the product of another model.
	What string

	// DueOn is the day the promise is due on.
	DueOn ledger.Date

	// MetOn is the day the promise was met. It is empty while the promise
	// is open: the day of meeting IS the state of the commitment.
	MetOn ledger.Date

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage
	// filled it on insert; whoever updates a row is responsible for it
	// after that.
	UpdatedAt time.Time
}

// Facts are the facts of a commitment that the storage holds.
//
// They are the row read back: the domain reads them through its own
// constructor, and the row never decides what a commitment is.
type Facts struct {
	// ID is the identity of the commitment.
	ID ID

	// BusinessID is the business that owes the promise.
	BusinessID business.ID

	// What is what is due, in the words of the owner.
	What string

	// DueOn is the day the promise is due on.
	DueOn ledger.Date

	// MetOn is the day the promise was met, and it is empty while the
	// promise is open.
	MetOn ledger.Date
}

// New builds the promise of the business.
//
// The rules of the domain hold here:
//
//   - the promise belongs to a business (ErrMissingBusiness);
//   - the promise says what is due: the "what" loses the spaces around it
//     and it may not be empty (ErrMissingWhat);
//   - the promise carries the day it is due (ErrMissingDay).
//
// The commitment is written OPEN: it carries no day of meeting.
func New(own business.ID, what string, dueOn ledger.Date) (Commitment, error) {
	if own <= 0 {
		return Commitment{}, fmt.Errorf("%w: the commitment is of the business %d", ErrMissingBusiness, own)
	}

	saying := strings.TrimSpace(what)
	if saying == "" {
		return Commitment{}, fmt.Errorf("%w: the commitment says %q", ErrMissingWhat, what)
	}

	if dueOn.Time().IsZero() {
		return Commitment{}, fmt.Errorf("%w: the commitment says %q and carries no day", ErrMissingDay, saying)
	}

	return Commitment{
		BusinessID: own,
		What:       saying,
		DueOn:      dueOn,
	}, nil
}

// NewFromFacts builds the commitment the storage holds.
//
// The rules of the domain hold here too: the promise belongs to a business,
// it says what is due, and it carries the day it is due. The state of the
// row is the state of the commitment: a row with no day of meeting is an
// open commitment, and a row that carries one is a promise that was kept.
//
// The error is ErrMissingBusiness when the promise is of no business,
// ErrMissingWhat when it says nothing about what is due, and ErrMissingDay
// when it carries no day.
func NewFromFacts(facts Facts) (Commitment, error) {
	if facts.BusinessID <= 0 {
		return Commitment{}, fmt.Errorf("%w: the commitment is of the business %d", ErrMissingBusiness, facts.BusinessID)
	}

	saying := strings.TrimSpace(facts.What)
	if saying == "" {
		return Commitment{}, fmt.Errorf("%w: the commitment says %q", ErrMissingWhat, facts.What)
	}

	if facts.DueOn.Time().IsZero() {
		return Commitment{}, fmt.Errorf("%w: the commitment says %q and carries no day", ErrMissingDay, saying)
	}

	return Commitment{
		ID:         facts.ID,
		BusinessID: facts.BusinessID,
		What:       saying,
		DueOn:      facts.DueOn,
		MetOn:      facts.MetOn,
	}, nil
}

// IsOpen reports whether the promise is still owed.
//
// The rule of the domain: the promise that was not met is still owed, and
// the promise that was met is kept with the day it was met. The day of
// meeting IS the state of the commitment: there is no state column that
// could say otherwise.
func (c Commitment) IsOpen() bool {
	return c.MetOn.Time().IsZero()
}

// Met answers the promise that was met on that day.
//
// The rules of the domain:
//
//   - the promise that was met is KEPT, with the day it was met
//     (ErrMissingMetDay): the promise that was kept is a fact of the book,
//     and a promise that was met with no day would look open for ever;
//   - a promise is kept once, and the promise that was met already is
//     refused (ErrAlreadyMet);
//   - the day it was met may be before or after the day it is due: a
//     promise kept early is kept, a promise kept late is late, and the book
//     never hides it. The domain does NOT know the day of today, so it
//     never refuses a day of meeting for being in the future.
func (c Commitment) Met(on ledger.Date) (Commitment, error) {
	if !c.IsOpen() {
		return Commitment{}, fmt.Errorf("%w: the commitment %d was met on %s", ErrAlreadyMet, c.ID, c.MetOn)
	}

	if on.Time().IsZero() {
		return Commitment{}, fmt.Errorf("%w: the commitment %d says %q", ErrMissingMetDay, c.ID, c.What)
	}

	met := c
	met.MetOn = on

	return met, nil
}

// OwnedBy states whether a business of that kind may hold commitments.
//
// The rule of the domain: the commitments belong to a business of its own,
// the one that sells the bread. The Personal Business of a person holds the
// money of that person, and not the promises of the bakery.
//
// The error is ErrWrongBusiness when the business is of another kind.
func OwnedBy(kind business.Kind) error {
	if kind != business.KindBusiness {
		return fmt.Errorf("%w: the kind of the business is %q, and the commitments belong to a business of its own",
			ErrWrongBusiness, kind)
	}

	return nil
}

// Calendar is the book of the promises read for a day: the promises that are
// due on it, and the ones that are still owed.
//
// The alarm is the work of the agent, and the calendar is what the agent
// reads to ring: PACA holds the fact, and the agent says it.
type Calendar struct {
	// Day is the day the calendar is read for. It is empty when the book
	// of the promises was read whole.
	Day ledger.Date

	// Due are the promises that are due on the day — and every promise of
	// the business when the day is not given: the book of the promises
	// read whole.
	Due []Commitment

	// Owed are the promises that are still owed: EVERY open promise of
	// the business, no matter the day it fell due on.
	Owed []Commitment
}

// TheCalendar answers the book of the promises for a day.
//
// The rule of the domain: the promises DUE on the day are the ones that are
// due on it, and a calendar with NO day carries every promise of the
// business: the book is read whole when the owner names no day.
//
// The calendar answers WHAT IS STILL OWED: every open promise of the
// business, the ones that are due on the day and the ones that fell due on
// an earlier day. This is the same rule the round of the orders carries: the
// promise that was not kept is owed, and the promise that was kept is not.
func TheCalendar(day ledger.Date, commitments []Commitment) Calendar {
	due := make([]Commitment, 0, len(commitments))
	owed := make([]Commitment, 0, len(commitments))

	for _, one := range commitments {
		if one.IsOpen() {
			owed = append(owed, one)
		}

		if !day.Time().IsZero() && !one.DueOn.Time().Equal(day.Time()) {
			continue
		}

		due = append(due, one)
	}

	return Calendar{Day: day, Due: due, Owed: owed}
}
