// Package ingredient holds the catalog of the names the business buys.
//
// The catalog begins empty and grows with what the owner buys: the name
// she reads and the names she uses for it. An ingredient is the thing the
// business buys, and it belongs to a business: two ingredients of the same
// business never carry the same name.
//
// The matching of a name she said is a rule of the domain: it answers
// exact, ambiguous - with the options it offers - or unknown. The order of
// the options is the order of the identity of the ingredients, so the
// answer is the same every time.
//
// A name the catalog does not know is not an error: it is recorded as she
// said it, and the answer tells her it is new.
//
// The package imports nothing but the standard library and the model of the
// business that owns the catalog.
package ingredient

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
)

// ID is the identity of an ingredient.
//
// The number is generated by the database: it is the counter of the
// ingredients and not a number of the person. The type exists so that an
// identifier never travels as a plain integer by accident.
type ID int64

// Ingredient is the thing the business buys.
//
// It carries the name the owner reads and the names she uses for it: the
// aliases. The aliases are what makes the catalog grow with the way she
// speaks, and not only with the way she writes.
//
// It carries also what the business knows of it and nobody else: the unit
// it is bought in, the weight of a package of it, the allergens it
// carries, the certification it has with the evidence of that
// certification, and the conversion of its raw grams into its prepared
// ones. Everything of it that the owner has not declared yet is empty,
// and the book says what is missing.
type Ingredient struct {
	// ID is the identity of the ingredient. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that buys it.
	BusinessID business.ID

	// Name is the name the owner reads.
	Name string

	// Aliases are the names the owner uses for it.
	Aliases []string

	// Unit is the unit the ingredient is bought in. It is empty when the
	// owner has not declared it yet.
	Unit Unit

	// PackageGrams is the weight of a package of the ingredient, in
	// grams. It is zero when the owner has not declared it yet, and it is
	// never assumed.
	PackageGrams float64

	// Allergens are the allergens the ingredient carries. They are the
	// ones the owner declared.
	Allergens []string

	// Certification is the claim the ingredient carries and the document
	// that proves it. It is empty when the ingredient carries no claim.
	Certification Certification

	// Conversion is the conversion of the raw into the prepared. It is
	// the one to one the owner decided for now, until she declares
	// another factor.
	Conversion Conversion

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage filled
	// it on insert; whoever updates a row is responsible for it after that.
	UpdatedAt time.Time
}

// New builds an ingredient of the catalog of a business.
//
// The name is the name the owner reads, and it may not be empty: an
// ingredient without a name has nothing to show in the book of its
// business.
//
// The aliases are the names she uses for it. They lose the spaces around
// them, an empty one is not an alias, the alias that is the name itself is
// not an alias, and the alias that is said twice is one alias: the name is
// compared the way a person reads it, trimmed and without case.
//
// The identity of the ingredient is not set here: the storage generates it,
// because the number is a counter of the ingredients and not a number of
// the person.
//
// The unit, the weight of a package, the allergens and the certification
// are empty: they are what the owner declares, through the tool that
// completes the ingredient. The conversion is the one to one she decided
// for now: the grams of a recipe are the raw ones.
func New(own business.ID, name string, aliases []string) (Ingredient, error) {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return Ingredient{}, fmt.Errorf("%w: the name of an ingredient is not empty", ErrInvalidName)
	}

	return Ingredient{
		BusinessID: own,
		Name:       trimmed,
		Aliases:    aliasesOf(trimmed, aliases),
		Conversion: Conversion{RawGrams: RawConversion},
	}, nil
}

// answers reports whether the ingredient answers the name the owner said.
//
// The name is compared the way a person reads it: trimmed, and without
// case. The aliases are the names she uses for it, and they answer too.
func (i Ingredient) answers(spoken string) bool {
	key := keyOf(spoken)
	if key == "" {
		return false
	}

	if keyOf(i.Name) == key {
		return true
	}

	for _, one := range i.Aliases {
		if keyOf(one) == key {
			return true
		}
	}

	return false
}

// aliasesOf answers the names the owner uses for the ingredient.
//
// The name itself is not an alias of the ingredient: it is its name. An
// alias that is said twice is one alias, and the first spelling is the one
// that is kept.
func aliasesOf(name string, aliases []string) []string {
	kept := make([]string, 0, len(aliases))
	seen := map[string]bool{keyOf(name): true}

	for _, one := range aliases {
		trimmed := strings.TrimSpace(one)
		if trimmed == "" {
			continue
		}

		key := keyOf(trimmed)
		if seen[key] {
			continue
		}

		seen[key] = true
		kept = append(kept, trimmed)
	}

	return kept
}

// keyOf answers the name the way a person reads it: trimmed, and without
// case.
func keyOf(name string) string {
	return strings.ToLower(strings.TrimSpace(name))
}
