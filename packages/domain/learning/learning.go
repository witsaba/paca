// Package learning holds the model of the learning log of the bakery: the
// memory of the errors and the wins of the owner.
//
// An entry of the log says what happened, in the words of the owner, and
// what was learned from it. It is about a DAY and about the bread: the batch
// the business bakes, and the run of that batch when the entry is about one
// run of it.
//
// The log carries NO money. It is not a sale, it is not a movement of the
// book and it never moves a peso: it is the memory the owner reads back, and
// the thing PACA learns from.
//
// The log is NEVER REWRITTEN. An entry is not updated and it is not deleted:
// a correction is a NEW entry that ANSWERS the old one, and the chain of the
// answers says which word is the last one. The entries that are the last
// word of their chain are what the owner already knows (Log.Current).
//
// The entry NAMES the batch and never copies it: the identity and the name
// of the recipe travel with the entry, and the recipe stays the owner of
// them. The production of T17 lives in the package of the recipe, and the
// entry of the log never becomes a second home for it.
//
// The package imports nothing but the standard library and the models it
// needs: the business that owns the log, the day of the book, and the batch
// and its production.
package learning

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ledger"
	"github.com/witsaba/paca/packages/domain/recipe"
)

// ID is the identity of an entry of the log.
//
// The number is generated by the database: it is the counter of the entries
// and not a number of the batch. The type exists so that an identifier never
// travels as a plain integer by accident.
//
// The identity of an entry is its OWN identity, never its text: two entries
// that say the same thing on the same day are two entries, and the book
// never merges them.
type ID int64

// Entry is one entry of the learning log: the day, the batch, what happened
// and what was learned.
//
// The entry is never rewritten. A correction is a NEW entry that answers the
// old one, and the entry that answers no other one and that no other one
// answers is the last word of its chain (Log.Current).
type Entry struct {
	// ID is the identity of the entry. It is empty until the storage writes
	// the row.
	ID ID

	// BusinessID is the business that owns the memory.
	BusinessID business.ID

	// Day is the day the entry is about.
	Day ledger.Date

	// RecipeID is the batch the entry is about: the recipe the business
	// bakes.
	RecipeID recipe.ID

	// RecipeName is the name the owner reads of the batch. It is the name of
	// the recipe, and the recipe is the owner of it.
	RecipeName string

	// ProductionID is the run of the batch the entry is about. It is empty
	// when the entry is about the batch alone.
	ProductionID recipe.ProductionID

	// Happened is what happened, in the words of the owner. It is never
	// empty, and it carries no space around it.
	Happened string

	// Learned is what was learned, in the words of the owner. It is never
	// empty, and it carries no space around it.
	Learned string

	// Answers is the entry this one answers. It is empty when the entry
	// answers no other one.
	Answers ID

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// Facts are the facts of an entry that the storage holds.
//
// They are the row read back: the domain reads them through its own
// constructor, and the row never decides what an entry of the log is.
type Facts struct {
	// ID is the identity of the entry.
	ID ID

	// BusinessID is the business that owns the memory.
	BusinessID business.ID

	// Day is the day the entry is about.
	Day ledger.Date

	// RecipeID is the batch the entry is about.
	RecipeID recipe.ID

	// RecipeName is the name the owner reads of the batch.
	RecipeName string

	// ProductionID is the run of the batch the entry is about, and it is
	// empty when the entry is about the batch alone.
	ProductionID recipe.ProductionID

	// Happened is what happened, in the words of the owner.
	Happened string

	// Learned is what was learned, in the words of the owner.
	Learned string

	// Answers is the entry this one answers, and it is empty when it answers
	// no other one.
	Answers ID
}

// New builds one entry of the log.
//
// The rules of the domain hold here:
//
//   - the entry belongs to a business (ErrMissingBusiness);
//   - it carries the day it is about (ErrMissingDay);
//   - it is about a batch: a recipe of the business that owns the entry
//     (ErrMissingRecipe), and never the recipe of another business
//     (ErrRecipeOfAnotherBusiness);
//   - the production, when the owner names it, is a production of the
//     business (ErrProductionOfAnotherBusiness) and a run of the NAMED batch
//     (ErrAnotherBatch): the production knows its own recipe, and the book
//     never carries two truths for the same fact;
//   - the entry says what happened (ErrMissingHappened) and what was learned
//     (ErrMissingLearned): the entry that says nothing is not an entry of
//     the log.
//
// The entry may answer another entry of the log (Answers). Whether that
// entry is there, of the business, and not answered yet is the rule of the
// log, and it is asked of the log (Log.Answering).
//
// The words of the owner lose the spaces around them, and the entry never
// invents them.
func New(
	own business.ID,
	day ledger.Date,
	batch recipe.Recipe,
	production *recipe.Production,
	happened, learned string,
	answers *ID,
) (Entry, error) {
	if own <= 0 {
		return Entry{}, fmt.Errorf("%w: the entry is of the business %d", ErrMissingBusiness, own)
	}

	if day.Time().IsZero() {
		return Entry{}, fmt.Errorf("%w: the business %d wrote it", ErrMissingDay, own)
	}

	if batch.ID == 0 {
		return Entry{}, fmt.Errorf("%w: the entry of the business %d is about no batch", ErrMissingRecipe, own)
	}

	if batch.BusinessID != own {
		return Entry{}, fmt.Errorf("%w: the batch %d is of the business %d and the entry is of the business %d",
			ErrRecipeOfAnotherBusiness, batch.ID, batch.BusinessID, own)
	}

	built := Entry{
		BusinessID: own,
		Day:        day,
		RecipeID:   batch.ID,
		RecipeName: batch.Name,
		Happened:   strings.TrimSpace(happened),
		Learned:    strings.TrimSpace(learned),
	}

	if production != nil {
		if production.BusinessID != own {
			return Entry{}, fmt.Errorf("%w: the production %d is of the business %d and the entry is of the business %d",
				ErrProductionOfAnotherBusiness, production.ID, production.BusinessID, own)
		}

		if production.RecipeID != batch.ID {
			return Entry{}, fmt.Errorf("%w: the production %d is a run of the batch %d and the entry names the batch %d",
				ErrAnotherBatch, production.ID, production.RecipeID, batch.ID)
		}

		built.ProductionID = production.ID
	}

	if built.Happened == "" {
		return Entry{}, fmt.Errorf("%w: the entry of the business %d says nothing happened", ErrMissingHappened, own)
	}

	if built.Learned == "" {
		return Entry{}, fmt.Errorf("%w: the entry of the business %d taught nothing", ErrMissingLearned, own)
	}

	if answers != nil {
		built.Answers = *answers
	}

	return built, nil
}

// NewFromFacts builds the entry of the log the storage holds.
//
// The rules of the domain hold here too: the entry belongs to a business, it
// carries the day it is about, it is about a batch, and it says what
// happened and what was learned. The batch of another business and the
// production of another batch are the rules of the write, and the table
// holds them with its composite foreign keys: a row that another writer
// broke is refused by the domain, and the adapter says it with ErrInvalidValue.
//
// The error is ErrMissingBusiness, ErrMissingDay, ErrMissingRecipe,
// ErrMissingHappened or ErrMissingLearned.
func NewFromFacts(facts Facts) (Entry, error) {
	if facts.BusinessID <= 0 {
		return Entry{}, fmt.Errorf("%w: the entry is of the business %d", ErrMissingBusiness, facts.BusinessID)
	}

	if facts.Day.Time().IsZero() {
		return Entry{}, fmt.Errorf("%w: the entry %d of the business %d", ErrMissingDay, facts.ID, facts.BusinessID)
	}

	if facts.RecipeID == 0 {
		return Entry{}, fmt.Errorf("%w: the entry %d of the business %d", ErrMissingRecipe, facts.ID, facts.BusinessID)
	}

	happened := strings.TrimSpace(facts.Happened)
	if happened == "" {
		return Entry{}, fmt.Errorf("%w: the entry %d of the business %d says nothing happened",
			ErrMissingHappened, facts.ID, facts.BusinessID)
	}

	learned := strings.TrimSpace(facts.Learned)
	if learned == "" {
		return Entry{}, fmt.Errorf("%w: the entry %d of the business %d taught nothing",
			ErrMissingLearned, facts.ID, facts.BusinessID)
	}

	return Entry{
		ID:           facts.ID,
		BusinessID:   facts.BusinessID,
		Day:          facts.Day,
		RecipeID:     facts.RecipeID,
		RecipeName:   facts.RecipeName,
		ProductionID: facts.ProductionID,
		Happened:     happened,
		Learned:      learned,
		Answers:      facts.Answers,
	}, nil
}

// OwnedBy states whether a business of that kind keeps a learning log.
//
// The rule of the domain: the log belongs to a business of its own, the one
// that sells the bread. The Personal Business of a person holds the money of
// that person, and not the lessons of the bakery.
//
// The error is ErrWrongBusiness when the business is of another kind.
func OwnedBy(kind business.Kind) error {
	if kind != business.KindBusiness {
		return fmt.Errorf("%w: the kind of the business is %q, and the log belongs to a business of its own",
			ErrWrongBusiness, kind)
	}

	return nil
}
