// Package ledger holds the model of the book of a business: the movements
// of the money and the balance of the accounts.
//
// The book is the sum of two facts: every movement of money is written in
// the book, and every account of the book carries the balance of its
// movements. Nothing else is in the book, and nothing in the book is
// anything else.
//
// A movement is money that goes from one account to another one: the debit
// account is where the money lands, and the credit account is where it
// comes from. The amount is positive, and the two sides of the movement are
// equal by the shape of the movement itself.
//
// The balance of an account is the difference between its debits and its
// credits, with the sign that the kind of the account asks for: what the
// person has and what they spend count as they are, and what the person
// owes, what they earn and what they put into the book count the other way
// round. The result reads "what it means to the person" in every kind.
//
// The package imports nothing but the standard library, the model of the
// business that owns the book and the model of the account.
package ledger

import (
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/account"
	"github.com/witsaba/paca/packages/domain/business"
)

// The errors of the domain of the book.
var (
	// ErrNotFound is the error of a business or of an account that the
	// storage does not hold.
	ErrNotFound = errors.New("there is no book for that business")

	// ErrNoStorage is the error of a port of the storage that has no
	// storage behind it.
	ErrNoStorage = errors.New("the storage of the book is not open")

	// ErrInvalidAmount is the error of a movement that carries no money.
	ErrInvalidAmount = errors.New("the amount of a movement is not zero")

	// ErrSameAccount is the error of a movement whose two sides are the
	// same account: money that goes nowhere.
	ErrSameAccount = errors.New("the two sides of a movement are not the same account")

	// ErrInvalidDate is the error of a day that is not a day.
	ErrInvalidDate = errors.New("the date is not a day of the book")

	// ErrInvalidDescription is the error of a movement without a
	// description: a movement the person cannot read is a movement they
	// cannot recognise.
	ErrInvalidDescription = errors.New("the description of a movement is not empty")
)

// Errors returns the errors of the domain of the book.
func Errors() []error {
	return []error{
		ErrNotFound,
		ErrNoStorage,
		ErrInvalidAmount,
		ErrSameAccount,
		ErrInvalidDate,
		ErrInvalidDescription,
	}
}

// Amount is a quantity of money.
//
// The amount is an integer, and never a float: the arithmetic of money does
// not forgive a rounding error, and the person reads the numbers that the
// book carries. The amount counts the units of the currency of the book,
// and the currency of PACA is the Colombian peso, whose smallest unit is
// the peso itself.
type Amount int64

// EntryID is the identity of a movement of the book.
//
// The number is generated by the database, and the type exists so that an
// identifier never travels as a plain integer by accident.
type EntryID int64

// Date is a day of the book.
//
// The book counts days, not moments: the time of the day is not a fact of
// the money.
type Date struct {
	moment time.Time
}

// NewDate returns the day of a moment.
//
// The moment is taken in UTC and the time of the day goes away: two moments
// of the same day are the same day of the book.
func NewDate(moment time.Time) Date {
	year, month, day := moment.UTC().Date()

	return Date{moment: time.Date(year, month, day, 0, 0, 0, 0, time.UTC)}
}

// ParseDate returns the day that a text carries.
//
// The day is written the way a person writes it: "2026-03-01". The error is
// ErrInvalidDate when the text is not a day.
func ParseDate(day string) (Date, error) {
	trimmed := strings.TrimSpace(day)

	moment, err := time.Parse("2006-01-02", trimmed)
	if err != nil {
		return Date{}, fmt.Errorf("%w: %q", ErrInvalidDate, day)
	}

	return NewDate(moment), nil
}

// String returns the day in the form a person writes it.
func (d Date) String() string {
	return d.moment.Format("2006-01-02")
}

// Time returns the moment of the day.
func (d Date) Time() time.Time {
	return d.moment
}

// Before reports whether the day is before the other one.
func (d Date) Before(other Date) bool {
	return d.moment.Before(other.moment)
}

// After reports whether the day is after the other one.
func (d Date) After(other Date) bool {
	return d.moment.After(other.moment)
}

// Entry is a movement of the book.
//
// Every movement is money that goes from the credit account to the debit
// account: the money lands where it is debited, and it comes from where it
// is credited. The amount is positive, and the two sides of the movement
// carry the same amount by the shape of the movement itself.
type Entry struct {
	// ID is the identity of the movement. It is empty until the storage
	// writes the row.
	ID EntryID

	// BusinessID is the business that owns the book of the movement.
	BusinessID business.ID

	// DebitAccountID is the account where the money lands.
	DebitAccountID account.ID

	// CreditAccountID is the account the money comes from.
	CreditAccountID account.ID

	// Amount is the money that moves. It is positive.
	Amount Amount

	// OccurredOn is the day of the movement.
	OccurredOn Date

	// Description is what the person reads in the book.
	Description string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// NewEntry builds a movement of the book.
//
// The amount is positive: the money moves, and how much of it moves is the
// fact of the movement. The two sides are not the same account: money that
// goes nowhere is not a movement. The description is not empty: a movement
// the person cannot read is a movement they cannot recognise.
//
// The identity of the movement is not set here: the storage generates it.
func NewEntry(
	businessID business.ID,
	debitAccountID, creditAccountID account.ID,
	amount Amount,
	occurredOn Date,
	description string,
) (Entry, error) {
	if amount <= 0 {
		return Entry{}, fmt.Errorf("%w: %d", ErrInvalidAmount, amount)
	}

	if debitAccountID == creditAccountID {
		return Entry{}, fmt.Errorf("%w: %d", ErrSameAccount, debitAccountID)
	}

	trimmed := strings.TrimSpace(description)
	if trimmed == "" {
		return Entry{}, fmt.Errorf("%w: the description of a movement is not empty", ErrInvalidDescription)
	}

	return Entry{
		BusinessID:      businessID,
		DebitAccountID:  debitAccountID,
		CreditAccountID: creditAccountID,
		Amount:          amount,
		OccurredOn:      occurredOn,
		Description:     trimmed,
	}, nil
}

// Balance is the balance of an account of the book.
//
// The two sums are the raw truth of the movements: what was debited to the
// account and what was credited to it. The balance the person reads is the
// difference between them, with the sign that the kind of the account asks
// for.
type Balance struct {
	// AccountID is the account the balance belongs to.
	AccountID account.ID

	// Kind is the kind of the account.
	Kind account.Kind

	// Name is the name the person reads in their book.
	Name string

	// Debits is the money that landed in the account.
	Debits Amount

	// Credits is the money that left the account.
	Credits Amount
}

// Normal returns the balance in the sense of the person.
//
// An asset and an expense count as they are: what the person has and what
// they spend are positive when they grow. A liability, an income and an
// equity count the other way round: what the person owes, what they earn
// and what they put into the book are positive when they grow.
func (b Balance) Normal() Amount {
	return Amount(b.Kind.NormalSign()) * (b.Debits - b.Credits)
}

// Book is the money of a business at a moment: what it has, what it owes
// and what it is worth.
//
// The three numbers are the reading of the book that the person understands:
// what they have, what they owe, and the difference between the two.
type Book struct {
	// BusinessID is the business the book belongs to.
	BusinessID business.ID

	// Assets is what the business has.
	Assets Amount

	// Liabilities is what the business owes.
	Liabilities Amount

	// Equity is what the owner put into the book of the business.
	Equity Amount

	// Income is what the business earned.
	Income Amount

	// Expenses is what the business spent.
	Expenses Amount
}

// NetWorth returns what the business is worth: what it has and what it
// owes.
//
// The net worth is the assets and the liabilities: the income and the
// expenses are already inside the assets, and counting them again would
// count the same money twice.
func (b Book) NetWorth() Amount {
	return b.Assets - b.Liabilities
}

// BookOf answers the money of a business from the balances of its accounts.
//
// The rule is the one of the accounting: the assets are the sum of the
// balances of the accounts that hold what the business has, and the same
// for the liabilities, the equity, the income and the expenses. The
// balances are the ones the person reads, sign and all.
func BookOf(businessID business.ID, balances []Balance) Book {
	book := Book{BusinessID: businessID}

	for _, balance := range balances {
		normal := balance.Normal()

		switch balance.Kind {
		case account.KindAsset:
			book.Assets += normal
		case account.KindLiability:
			book.Liabilities += normal
		case account.KindEquity:
			book.Equity += normal
		case account.KindIncome:
			book.Income += normal
		case account.KindExpense:
			book.Expenses += normal
		}
	}

	return book
}
