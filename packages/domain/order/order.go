// Package order holds the model of the order of the bakery: what the
// bakery owes and the round that carries it.
//
// An order is a fact of the business: the party that ordered, the products
// it ordered with the quantities of them, and the day it is due. The order
// NAMES the party and the products: it never copies the client and never
// copies the product, and the models it needs are imported and not
// rewritten.
//
// The order is written OPEN, and the domain owns the state of it: an order
// that was not delivered stays open. The delivery of an order is written
// with the ROUTE of the round: the route is what the agent computes when it
// comes back from the round, and the increment that writes the route writes
// the delivery with it.
//
// The ROUND is the day and the orders it carries: the orders that are due
// on that day. The round answers WHAT IS STILL OWED: the orders it carries
// that were not delivered.
//
// The money of an order is NOT part of this model: the acceptance of the
// increment does not state it, and the book never adds a rule nobody
// wrote. Whether the order carries the money of the price list of the day
// it was made is a question of the owner, and it waits for her.
//
// The package imports nothing but the standard library and the models it
// needs: the business that owns the order, the party that ordered, the
// product that was ordered and the day of the book.
package order

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ledger"
	"github.com/witsaba/paca/packages/domain/party"
	"github.com/witsaba/paca/packages/domain/product"
)

// ID is the identity of an order.
//
// The number is generated by the database: it is the counter of the orders
// and not a number of the party. The type exists so that an identifier
// never travels as a plain integer by accident.
type ID int64

// State is the state of an order.
//
// The states are the two of the book: the order that waits for the round
// that carries it, and the order that was delivered. An order that was not
// delivered stays open, and the round of the day answers what is still
// owed: the orders that are open.
//
// The delivery of an order is written with the ROUTE of the round, and the
// route is written by the increment that comes after this one: the
// transition from the open order to the delivered one belongs to that
// increment, and the domain of the order is where it lands.
type State string

const (
	// StateOpen is the state of the order that was not delivered.
	//
	// The order is written open, and it stays open until the round that
	// carries it delivers it.
	StateOpen State = "open"

	// StateDelivered is the state of the order that the round delivered.
	//
	// The delivery is written with the route of the round.
	StateDelivered State = "delivered"
)

// states holds the states of an order, in the order they are presented.
var states = []State{
	StateOpen,
	StateDelivered,
}

// AllStates returns the states of an order.
//
// The caller receives a copy: the order and the content of the list never
// change under it. The contract that the agent reads is derived from this
// list, and it never restates it.
func AllStates() []State {
	all := make([]State, len(states))
	copy(all, states)

	return all
}

// Valid reports whether the state is one of the states of an order.
func (s State) Valid() bool {
	for _, candidate := range states {
		if s == candidate {
			return true
		}
	}

	return false
}

// String returns the name of the state.
//
// It is the name the storage holds, with no translation in between.
func (s State) String() string {
	return string(s)
}

// ParseState returns the state of the given name.
//
// The storage refuses a name that is not one of the states of an order, so
// a name that fails here would fail there too. The error wraps
// ErrUnknownState, so a caller can tell an unknown state from a failure of
// something else.
func ParseState(name string) (State, error) {
	state := State(strings.TrimSpace(name))
	if !state.Valid() {
		return "", fmt.Errorf("%w: %q", ErrUnknownState, name)
	}

	return state, nil
}

// Line is one line of an order: the product, the quantity of it and the
// unit the owner said.
//
// The quantity is a whole number of units: the book never splits a unit and
// it never converts a weight into a number of units. The unit is the unit
// the owner said, and it travels with the quantity.
type Line struct {
	// ProductID is the product the line is of.
	ProductID product.ID

	// ProductName is the name the owner reads of the product.
	//
	// The name is the one of the product, and the product is its owner:
	// the order carries the name the owner read when she ordered.
	ProductName string

	// Quantity is how many units of the product the line carries.
	Quantity int

	// Unit is the unit of that quantity, the way the owner said it.
	Unit string
}

// LineDefinition is what the owner said about a line of the order.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type LineDefinition struct {
	// Product is the product the line is of.
	Product product.Product

	// Quantity is how many units of the product the line carries.
	Quantity int

	// Unit is the unit of that quantity, the way the owner said it.
	Unit string
}

// Order is the order of the business: what the bakery owes to a party, and
// the day it is due.
//
// The order carries its lines: the products with the quantities of them and
// the units the owner said.
type Order struct {
	// ID is the identity of the order. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that owns the order and that owes it.
	BusinessID business.ID

	// PartyID is the party that ordered: the client of the business.
	PartyID party.ID

	// PartyName is the name the owner reads of the party that ordered.
	//
	// The name is the one of the party, and the party is its owner.
	PartyName string

	// DueOn is the day the order is due on.
	DueOn ledger.Date

	// Lines are the lines of the order: the products with the quantities
	// of them and the units the owner said.
	Lines []Line

	// State is the state of the order: the open one, or the delivered
	// one.
	State State

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage
	// filled it on insert; whoever updates a row is responsible for it
	// after that.
	UpdatedAt time.Time
}

// Facts are the facts of an order that the storage holds.
//
// They are the row read back: the domain reads them through its own
// constructor, and the row never decides what an order is.
type Facts struct {
	// ID is the identity of the order.
	ID ID

	// BusinessID is the business that owns the order.
	BusinessID business.ID

	// PartyID is the party that ordered.
	PartyID party.ID

	// PartyName is the name the owner reads of the party that ordered.
	PartyName string

	// DueOn is the day the order is due on.
	DueOn ledger.Date

	// Lines are the lines of the order.
	Lines []Line

	// State is the state of the order.
	State State
}

// New builds the order of the business.
//
// The rules of the domain hold here:
//
//   - the order belongs to a business (ErrMissingBusiness);
//   - the order names the party that ordered, and the party is a client
//     of the business (ErrMissingParty, ErrNotAClient);
//   - the party is a party of the business that owns the order
//     (ErrPartyOfAnotherBusiness);
//   - the order carries at least one line: an order without a line orders
//     nothing (ErrNoLines);
//   - every line names a product of the price list of the business
//     (ErrMissingProduct, ErrProductOfAnotherBusiness);
//   - the quantity of a line is a positive whole number of units: the book
//     never splits a unit (ErrInvalidQuantity);
//   - the line carries the unit the owner said (ErrMissingUnit);
//   - the order carries the day it is due (ErrMissingDay).
//
// The order is written OPEN: an order that was not delivered stays open.
func New(own business.ID, client party.Party, dueOn ledger.Date, lines []LineDefinition) (Order, error) {
	if own <= 0 {
		return Order{}, fmt.Errorf("%w: the order is of the business %d", ErrMissingBusiness, own)
	}

	if client.ID == 0 {
		return Order{}, fmt.Errorf("%w: the order names no party", ErrMissingParty)
	}

	if client.BusinessID != own {
		return Order{}, fmt.Errorf("%w: the party %d belongs to the business %d and the order is of the business %d",
			ErrPartyOfAnotherBusiness, client.ID, client.BusinessID, own)
	}

	if !client.Is(party.RoleClient) {
		return Order{}, fmt.Errorf("%w: the party %d holds the roles %v",
			ErrNotAClient, client.ID, client.Roles)
	}

	if len(lines) == 0 {
		return Order{}, fmt.Errorf("%w: the order carries no line", ErrNoLines)
	}

	built := make([]Line, 0, len(lines))

	for _, one := range lines {
		if one.Product.ID == 0 {
			return Order{}, fmt.Errorf("%w: the line of the order names no product", ErrMissingProduct)
		}

		if one.Product.BusinessID != own {
			return Order{}, fmt.Errorf("%w: the product %d belongs to the business %d and the order is of the business %d",
				ErrProductOfAnotherBusiness, one.Product.ID, one.Product.BusinessID, own)
		}

		if one.Quantity <= 0 {
			return Order{}, fmt.Errorf("%w: the line carries %d units", ErrInvalidQuantity, one.Quantity)
		}

		unit := strings.TrimSpace(one.Unit)
		if unit == "" {
			return Order{}, fmt.Errorf("%w: the line carries no unit", ErrMissingUnit)
		}

		built = append(built, Line{
			ProductID:   one.Product.ID,
			ProductName: one.Product.Name,
			Quantity:    one.Quantity,
			Unit:        unit,
		})
	}

	if dueOn.Time().IsZero() {
		return Order{}, fmt.Errorf("%w: the order carries no day", ErrMissingDay)
	}

	return Order{
		BusinessID: own,
		PartyID:    client.ID,
		PartyName:  client.Name,
		DueOn:      dueOn,
		Lines:      built,
		State:      StateOpen,
	}, nil
}

// NewFromFacts builds the order the storage holds.
//
// The rules of the domain hold here too: the order names a party, carries
// the day it is due, carries its lines and carries its state. The state of
// the row is the state of the order: an order that was not delivered stays
// open, and the order that the round delivered carries the state of its
// delivery.
//
// The error is ErrMissingBusiness when the order is of no business,
// ErrMissingParty when it names no party, ErrMissingDay when it carries no
// day, ErrNoLines when it carries no line, ErrInvalidQuantity when the
// quantity of a line is not a whole number of units, ErrMissingUnit when a
// line carries no unit, and ErrUnknownState when the state is not one of
// the states of the book.
func NewFromFacts(facts Facts) (Order, error) {
	if facts.BusinessID <= 0 {
		return Order{}, fmt.Errorf("%w: the order is of the business %d", ErrMissingBusiness, facts.BusinessID)
	}

	if facts.PartyID == 0 {
		return Order{}, fmt.Errorf("%w: the order names no party", ErrMissingParty)
	}

	if facts.DueOn.Time().IsZero() {
		return Order{}, fmt.Errorf("%w: the order carries no day", ErrMissingDay)
	}

	if len(facts.Lines) == 0 {
		return Order{}, fmt.Errorf("%w: the order carries no line", ErrNoLines)
	}

	lines := make([]Line, 0, len(facts.Lines))

	for _, one := range facts.Lines {
		if one.ProductID == 0 {
			return Order{}, fmt.Errorf("%w: the line of the order names no product", ErrMissingProduct)
		}

		if one.Quantity <= 0 {
			return Order{}, fmt.Errorf("%w: the line carries %d units", ErrInvalidQuantity, one.Quantity)
		}

		unit := strings.TrimSpace(one.Unit)
		if unit == "" {
			return Order{}, fmt.Errorf("%w: the line carries no unit", ErrMissingUnit)
		}

		lines = append(lines, Line{
			ProductID:   one.ProductID,
			ProductName: strings.TrimSpace(one.ProductName),
			Quantity:    one.Quantity,
			Unit:        unit,
		})
	}

	state, err := ParseState(facts.State.String())
	if err != nil {
		return Order{}, err
	}

	return Order{
		ID:         facts.ID,
		BusinessID: facts.BusinessID,
		PartyID:    facts.PartyID,
		PartyName:  strings.TrimSpace(facts.PartyName),
		DueOn:      facts.DueOn,
		Lines:      lines,
		State:      state,
	}, nil
}

// IsOpen reports whether the order is still owed.
//
// The rule of the domain: an order that was not delivered stays open, and
// the round of the day answers what is still owed: the orders that are
// open.
func (o Order) IsOpen() bool {
	return o.State == StateOpen
}

// OwnedBy states whether a business of that kind may hold orders.
//
// The rule of the domain: the orders belong to the business of the bakery,
// the one that sells the bread. The Personal Business of a person holds
// the money of that person, and not the orders of the bakery.
//
// The error is ErrWrongBusiness when the business is of another kind.
func OwnedBy(kind business.Kind) error {
	if kind != business.KindBusiness {
		return fmt.Errorf("%w: the kind of the business is %q, and the orders belong to a business of its own",
			ErrWrongBusiness, kind)
	}

	return nil
}

// Round is the round of a day: the day and the orders it carries.
//
// The round answers what is still owed: the orders it carries that were
// not delivered.
type Round struct {
	// Day is the day the round is of.
	Day ledger.Date

	// Orders are the orders the round carries.
	Orders []Order
}

// TheRound answers the round of a day: the orders it carries.
//
// The rule of the domain: the round of a day carries the orders that are
// DUE on it: the bread the bakery owes that day.
//
// A round with NO day carries every order of the business: the book of the
// orders is read whole when the owner names no day.
func TheRound(day ledger.Date, orders []Order) Round {
	carried := make([]Order, 0, len(orders))

	for _, one := range orders {
		if !day.Time().IsZero() && !one.DueOn.Time().Equal(day.Time()) {
			continue
		}

		carried = append(carried, one)
	}

	return Round{Day: day, Orders: carried}
}

// Owed answers the orders of the round that are still owed.
//
// The rule of the domain: an order that was not delivered stays open, and
// the round of the day answers what is still owed: the open orders it
// carries.
func (r Round) Owed() []Order {
	owed := make([]Order, 0, len(r.Orders))

	for _, one := range r.Orders {
		if !one.IsOpen() {
			continue
		}

		owed = append(owed, one)
	}

	return owed
}
