// Package party holds the model of the party of the business: the person,
// the store and the farm that buy from the bakery or that the bakery buys
// from.
//
// A party is the other side of the bread: the client that buys it and the
// provider that sells the flour of it. The two are the same model, because
// the owner of the bakery buys from a farm and sells to a person, and
// neither of them is a second business.
//
// The legal human that represents a store or a farm is a FACT OF THE PARTY:
// it is a name and, when there is one, a legal figure. It is never a second
// person: it is not a user of PACA, it is not a party of its own, and it
// never becomes a row of the people of PACA. The party carries it, and the
// book of the business reads it with the party.
//
// The tax identity of the party — the NIT of a person, of a store or of a
// farm — is a fact of the party too, and it is OPTIONAL: the book never
// asks for it, and it never assumes one. The book does not know the format
// of a tax identity either: it is kept the way the owner said it, and the
// rule of the tax authority and the advice of the professional of the owner
// are not read here.
//
// The way of reaching the party and its address are facts of the party too.
// The rules of the phone and of the email are the ones of the person, and
// the package reuses them: the party never writes a second cleaning rule.
//
// The party belongs to the business that knows it: a party of a business of
// kind business, and the business owns it. The Personal Business of a
// person holds the money of that person, and not the clients and the
// providers of the bakery.
//
// The name of a party is NOT unique inside the business: the book never
// refuses two parties that share a name, and the reading of the parties
// lists them all.
//
// The package imports nothing but the standard library and the models of
// the business and of the person: the owner of a party is a business, and
// the way of reaching it is the way of reaching a person.
package party

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/user"
)

// ID is the identity of a party.
//
// The number is generated by the database: it is the counter of the parties
// and not a number of the person. The type exists so that an identifier
// never travels as a plain integer by accident.
type ID int64

// Kind is the kind of a party.
//
// The kinds are the three of the owner: the person, the store and the farm.
// The kind decides what the party carries: the store is represented by a
// legal human and the farm may carry one.
type Kind string

const (
	// KindPerson is the kind of a party that is a person.
	//
	// The person is never represented by a legal human: it is a person,
	// and the domain refuses a legal human in it.
	KindPerson Kind = "person"

	// KindStore is the kind of a party that is a store.
	//
	// The store is represented by a legal human, and the domain refuses a
	// store that carries none.
	KindStore Kind = "store"

	// KindFarm is the kind of a party that is a farm.
	//
	// The farm may carry a legal figure and it may carry none: some
	// farms have one and some do not.
	KindFarm Kind = "farm"
)

// kinds holds the kinds of a party, in the order they are presented.
var kinds = []Kind{
	KindPerson,
	KindStore,
	KindFarm,
}

// AllKinds returns the kinds of a party.
//
// The caller receives a copy: the order and the content of the list never
// change under it. The contract that the agent reads is derived from this
// list, and it never restates it.
func AllKinds() []Kind {
	all := make([]Kind, len(kinds))
	copy(all, kinds)
	return all
}

// Valid reports whether the kind is one of the kinds of a party.
func (k Kind) Valid() bool {
	for _, candidate := range kinds {
		if k == candidate {
			return true
		}
	}
	return false
}

// String returns the name of the kind.
//
// It is the name the storage holds, with no translation in between.
func (k Kind) String() string {
	return string(k)
}

// ParseKind returns the kind of the given name.
//
// The storage refuses a name that is not one of the kinds of a party, so a
// name that fails here would fail there too. The error wraps
// ErrUnknownKind, so a caller can tell an unknown kind from a failure of
// something else.
func ParseKind(name string) (Kind, error) {
	kind := Kind(strings.TrimSpace(name))
	if !kind.Valid() {
		return "", fmt.Errorf("%w: %q", ErrUnknownKind, name)
	}
	return kind, nil
}

// Role is the role a party holds in the business.
//
// The roles are the two of the owner: the client that buys from the bakery
// and the provider that the bakery buys from. A party may hold both, and it
// may hold neither only when it holds none: a party the bakery neither
// sells to nor buys from is not a party of the book.
type Role string

const (
	// RoleClient is the role of the party that buys from the business.
	RoleClient Role = "client"

	// RoleProvider is the role of the party that the business buys from.
	RoleProvider Role = "provider"
)

// roles holds the roles of a party, in the order they are presented.
var roles = []Role{
	RoleClient,
	RoleProvider,
}

// AllRoles returns the roles of a party.
//
// The caller receives a copy: the order and the content of the list never
// change under it. The contract that the agent reads is derived from this
// list, and it never restates it.
func AllRoles() []Role {
	all := make([]Role, len(roles))
	copy(all, roles)
	return all
}

// Valid reports whether the role is one of the roles of a party.
func (r Role) Valid() bool {
	for _, candidate := range roles {
		if r == candidate {
			return true
		}
	}
	return false
}

// String returns the name of the role.
//
// It is the name the storage holds, with no translation in between.
func (r Role) String() string {
	return string(r)
}

// ParseRole returns the role of the given name.
//
// The error wraps ErrUnknownRole, so a caller can tell an unknown role from
// a failure of something else.
func ParseRole(name string) (Role, error) {
	role := Role(strings.TrimSpace(name))
	if !role.Valid() {
		return "", fmt.Errorf("%w: %q", ErrUnknownRole, name)
	}
	return role, nil
}

// ParseRoles returns the roles of the given names.
//
// The list is empty when the caller named none: the domain refuses the
// party that holds no role at all, and it is the party that refuses it.
//
// The error wraps ErrUnknownRole when one of the names is not a role of a
// party.
func ParseRoles(names []string) ([]Role, error) {
	parsed := make([]Role, 0, len(names))

	for _, name := range names {
		role, err := ParseRole(name)
		if err != nil {
			return nil, err
		}

		parsed = append(parsed, role)
	}

	return parsed, nil
}

// LegalHuman is the human that represents a party that is not a person.
//
// It is a FACT OF THE PARTY and never a second person: it is not a user of
// PACA, it is not a party of its own, and it never becomes a row of the
// people of PACA. It carries the name of the human and, when there is one,
// the legal figure it has.
type LegalHuman struct {
	// Name is the name of the human that represents the party.
	Name string

	// Figure is the legal figure the human has ('S.A.S.', 'Ltda.'). It is
	// empty when the human has none.
	Figure string
}

// NewLegalHuman builds the human that represents a party.
//
// The name loses the spaces around it and it may not be empty: a legal
// figure without the name of the human it belongs to is a figure of nobody.
//
// The figure loses the spaces around it too, and it is optional: some farms
// have a legal figure and some do not.
func NewLegalHuman(name, figure string) (LegalHuman, error) {
	trimmedName := strings.TrimSpace(name)
	if trimmedName == "" {
		return LegalHuman{}, fmt.Errorf("%w: the name of the legal human is not empty", ErrMissingLegalHuman)
	}

	return LegalHuman{
		Name:   trimmedName,
		Figure: strings.TrimSpace(figure),
	}, nil
}

// Party is a party of the business: the person, the store or the farm that
// buys from it or that it buys from.
type Party struct {
	// ID is the identity of the party. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that knows the party and that owns it.
	BusinessID business.ID

	// Kind is the kind of the party.
	Kind Kind

	// Name is the name the owner reads.
	//
	// The name is not unique inside the business: the book never refuses
	// two parties that share a name.
	Name string

	// Roles are the roles the party holds: the client, the provider, or
	// both of them.
	Roles []Role

	// Phone is the phone number of the party, as digits with the country
	// code. It is empty when the owner did not declare one.
	Phone string

	// Email is the email address of the party. It is empty when the owner
	// did not declare one.
	Email string

	// Address is the address of the party. It is empty when the owner did
	// not declare one.
	Address string

	// TaxID is the tax identity of the party: the NIT of a person, of a
	// store or of a farm.
	//
	// It is OPTIONAL, and nothing in the book assumes one: a party may
	// carry it and a party may carry none. The book does not know the
	// format of a tax identity and it never reads one: the rule of the
	// tax authority and the advice of the professional of the owner are
	// not read here.
	TaxID string

	// LegalHuman is the human that represents the party. It is empty when
	// the party has none: a person never has one, and a farm may have
	// none.
	LegalHuman LegalHuman

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage filled
	// it on insert; whoever updates a row is responsible for it after that.
	UpdatedAt time.Time
}

// New builds a party of the domain.
//
// The name loses the spaces around it, and it may not be empty: a party
// without a name has nothing to show in the book of its business.
//
// The roles are the roles the party holds, and it holds at least one: the
// client, the provider, or both of them. A role that is said twice is one
// role.
//
// The way of reaching the party is cleaned the way the way of reaching a
// person is cleaned: the phone loses the punctuation of the way a person
// writes it, and the email is checked and stored in its canonical form. The
// rules are the ones of the person, and the package reuses them.
//
// The legal human is the human that represents the party, and the kind
// decides what the party carries: the store requires one and the domain
// refuses a store without it, the farm may carry one and the domain refuses
// a farm whose legal figure has no name, and the person refuses one.
//
// The identity of the party is not set here: the storage generates it,
// because the number is a counter of the parties and not a number of the
// person.
func New(
	own business.ID,
	kind Kind,
	name string,
	roles []Role,
	phone, email, address string,
	human LegalHuman,
) (Party, error) {
	if !kind.Valid() {
		return Party{}, fmt.Errorf("%w: %q", ErrUnknownKind, kind)
	}

	trimmedName := strings.TrimSpace(name)
	if trimmedName == "" {
		return Party{}, fmt.Errorf("%w: the name of a party is not empty", ErrInvalidName)
	}

	held, err := rolesOf(roles)
	if err != nil {
		return Party{}, err
	}

	cleanPhone, err := user.CleanPhone(phone)
	if err != nil {
		return Party{}, err
	}

	cleanEmail, err := user.CleanEmail(email)
	if err != nil {
		return Party{}, err
	}

	legal, err := legalHumanOf(kind, human)
	if err != nil {
		return Party{}, err
	}

	return Party{
		BusinessID: own,
		Kind:       kind,
		Name:       trimmedName,
		Roles:      held,
		Phone:      cleanPhone,
		Email:      cleanEmail,
		Address:    strings.TrimSpace(address),
		LegalHuman: legal,
	}, nil
}

// WithTaxIdentity answers the party carrying that tax identity.
//
// The tax identity is an OPTIONAL fact of the party: the identity loses the
// spaces around it, and an empty one leaves the party as it was. The book
// does not know the format of a tax identity and it never reads one: the
// tax identity is kept the way the owner said it.
func (p Party) WithTaxIdentity(taxID string) Party {
	p.TaxID = strings.TrimSpace(taxID)

	return p
}

// Is reports whether the party holds that role.
func (p Party) Is(role Role) bool {
	for _, held := range p.Roles {
		if held == role {
			return true
		}
	}
	return false
}

// OwnedBy states whether a business of that kind may own parties.
//
// The rule of the domain: the parties belong to a business of its own, the
// one that has the clients and the providers of the bakery. The Personal
// Business of a person holds the money of that person, and not the book of
// the bakery.
//
// The error is ErrWrongBusiness when the business is of another kind.
func OwnedBy(kind business.Kind) error {
	if kind != business.KindBusiness {
		return fmt.Errorf("%w: the kind of the business is %q, and the parties belong to a business of its own",
			ErrWrongBusiness, kind)
	}

	return nil
}

// rolesOf returns the roles the party holds.
//
// The party holds at least one role: the client, the provider, or both of
// them. A party that the bakery neither sells to nor buys from is not a
// party of the book, and the domain refuses it.
//
// A role that is said twice is one role, and the first spelling is the one
// that is kept.
func rolesOf(held []Role) ([]Role, error) {
	if len(held) == 0 {
		return nil, fmt.Errorf("%w: a party holds the role of the client or the role of the provider", ErrNoRole)
	}

	kept := make([]Role, 0, len(held))
	seen := make(map[Role]bool, len(held))

	for _, role := range held {
		if !role.Valid() {
			return nil, fmt.Errorf("%w: %q", ErrUnknownRole, role)
		}
		if seen[role] {
			continue
		}

		seen[role] = true
		kept = append(kept, role)
	}

	return kept, nil
}

// legalHumanOf returns the legal human the party of that kind carries.
//
// The rule of the domain: the store requires the legal human that
// represents it, the farm carries one only when it has one, and the person
// refuses one.
func legalHumanOf(kind Kind, human LegalHuman) (LegalHuman, error) {
	name := strings.TrimSpace(human.Name)
	figure := strings.TrimSpace(human.Figure)

	switch kind {
	case KindPerson:
		if name != "" || figure != "" {
			return LegalHuman{}, fmt.Errorf("%w: a person is not represented by a legal human", ErrUnexpectedLegalHuman)
		}
		return LegalHuman{}, nil
	case KindStore:
		if name == "" {
			return LegalHuman{}, fmt.Errorf("%w: a store is represented by a legal human", ErrMissingLegalHuman)
		}
		return LegalHuman{Name: name, Figure: figure}, nil
	default:
		if name == "" {
			if figure != "" {
				return LegalHuman{}, fmt.Errorf("%w: a legal figure has no name", ErrMissingLegalHuman)
			}
			return LegalHuman{}, nil
		}
		return LegalHuman{Name: name, Figure: figure}, nil
	}
}
