// Package product holds the model of the product of the bakery: the thing
// the bakery sells, the channel that buys it and the price it carries.
//
// The product of the bakery IS the thing it sells: it carries the recipe
// it comes from — the bakery sells what it bakes — and the name the owner
// reads. A product is never a second copy of the recipe: it carries the
// identity of it and nothing else.
//
// The CHANNEL is the way the product is bought: the retail, the person who
// buys a loaf at the door, and the wholesale, the store that buys many of
// them. The two are the vocabulary of the book, and the domain reads the
// two ways the owner says them: "retail" and "minorista" are the same
// channel, and so are "wholesale" and "mayorista".
//
// The CHANNEL IS ALREADY IN THE PRICE from the first row: every price
// carries the channel it was set for, so that the discount of the
// wholesale never has to rebuild the history of the prices. There is no
// "the price without a channel" and there is no default channel.
//
// The price is a FACT with the day it was set, and the price list is a
// history: the rows are kept, nothing is rewritten when a price changes,
// and the price that holds today for a product and a channel is the last
// one set on or before the day that is asked for.
//
// The price of a product is a fact of the BUSINESS, and it never becomes a
// column of the inventory, of the recipe or of the stock: the price lives
// in the table of the prices, with a row of its own.
//
// The tax treatment of a product is an ATTRIBUTE OF THE PRODUCT, and it is
// OPTIONAL: an empty one means the owner has not decided it, and the book
// never derives it from the price and never assumes a rate. The treatment
// is the fact the owner states, and nothing more: the rule of the tax
// authority and the advice of the professional of the owner are not read
// here.
//
// The package imports nothing but the standard library, the model of the
// business that owns the price list, the model of the recipe the product
// comes from and the money of the book.
package product

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ledger"
	"github.com/witsaba/paca/packages/domain/recipe"
)

// ID is the identity of a product.
//
// The number is generated by the database: it is the counter of the
// products and not a number of the recipe. The type exists so that an
// identifier never travels as a plain integer by accident.
type ID int64

// PriceID is the identity of a price.
//
// The number is generated by the database: it is the counter of the prices
// and not a number of the product. The type exists so that an identifier
// never travels as a plain integer by accident.
type PriceID int64

// Channel is the way the product of the bakery is bought.
//
// The channels are the two of the owner: the retail, the person who buys
// at the door, and the wholesale, the store that buys many of them.
//
// The owner thinks of the stores: she says "minorista" and "mayorista",
// and the book of PACA speaks in English. The domain reads the two ways of
// saying them, and the storage holds the one of the book.
type Channel string

const (
	// ChannelRetail is the channel of the client that buys at the door.
	ChannelRetail Channel = "retail"

	// ChannelWholesale is the channel of the store that buys many of
	// them.
	ChannelWholesale Channel = "wholesale"
)

// channels holds the channels of the book, in the order they are presented.
var channels = []Channel{
	ChannelRetail,
	ChannelWholesale,
}

// AllChannels returns the channels of the book.
//
// The caller receives a copy: the order and the content of the list never
// change under it. The contract that the agent reads is derived from this
// list, and it never restates it.
func AllChannels() []Channel {
	all := make([]Channel, len(channels))
	copy(all, channels)

	return all
}

// Valid reports whether the channel is one of the channels of the book.
func (c Channel) Valid() bool {
	for _, candidate := range channels {
		if c == candidate {
			return true
		}
	}

	return false
}

// String returns the name of the channel.
//
// It is the name the storage holds, with no translation in between.
func (c Channel) String() string {
	return string(c)
}

// ParseChannel returns the channel of the given name.
//
// The name is read the way the owner says it: the name of the book and the
// name of hers are the same channel, and the spaces around it and its case
// are not part of it.
//
// The error wraps ErrUnknownChannel, so a caller can tell an unknown
// channel from a failure of something else.
func ParseChannel(name string) (Channel, error) {
	said := strings.ToLower(strings.TrimSpace(name))

	switch said {
	case string(ChannelRetail), "minorista":
		return ChannelRetail, nil
	case string(ChannelWholesale), "mayorista":
		return ChannelWholesale, nil
	}

	return "", fmt.Errorf("%w: %q", ErrUnknownChannel, name)
}

// Product is the thing the bakery sells.
//
// The product carries the recipe it comes from and the name the owner
// reads. The tax treatment is an optional fact of it: the owner has not
// decided it yet, and the book never decides it for her.
type Product struct {
	// ID is the identity of the product. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that owns the product and that holds
	// its price list.
	BusinessID business.ID

	// RecipeID is the recipe the product comes from: the bakery sells
	// what it bakes.
	RecipeID recipe.ID

	// Name is the name the owner reads.
	//
	// The name is not unique inside the business: the book refuses two
	// products of a business that share it.
	Name string

	// TaxTreatment is the tax treatment the owner stated for the
	// product.
	//
	// It is OPTIONAL, and the book never derives it: an empty one means
	// the owner has not decided it, and there is no default rate and no
	// catalogue of treatments here.
	TaxTreatment string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage filled
	// it on insert; whoever updates a row is responsible for it after that.
	UpdatedAt time.Time
}

// New builds the product of a business.
//
// The rules of the domain hold here:
//
//   - the product comes from a recipe: the bakery sells what it bakes
//     (ErrMissingRecipe);
//   - the name the owner reads is not empty: the name is never guessed
//     (ErrInvalidName).
//
// The tax treatment is optional and it is the fact the owner stated: the
// book never derives it from the price and never assumes a rate.
func New(own business.ID, from recipe.ID, name, treatment string) (Product, error) {
	if from == 0 {
		return Product{}, fmt.Errorf("%w: the product names no recipe", ErrMissingRecipe)
	}

	trimmedName := strings.TrimSpace(name)
	if trimmedName == "" {
		return Product{}, fmt.Errorf("%w: the name of a product is not empty", ErrInvalidName)
	}

	return Product{
		BusinessID:   own,
		RecipeID:     from,
		Name:         trimmedName,
		TaxTreatment: strings.TrimSpace(treatment),
	}, nil
}

// WithTaxTreatment answers the product carrying that tax treatment.
//
// The tax treatment is an OPTIONAL fact of the product: the treatment loses
// the spaces around it, and an empty one leaves the product as it was. The
// book never derives it from the price and never assumes a rate: the
// treatment is the fact the owner stated.
func (p Product) WithTaxTreatment(treatment string) Product {
	trimmed := strings.TrimSpace(treatment)
	if trimmed == "" {
		return p
	}

	p.TaxTreatment = trimmed

	return p
}

// TheProduct answers the product the owner names, and opens the one that
// is not there yet.
//
// The rules of the domain hold here:
//
//   - the product comes from a recipe: the bakery sells what it bakes
//     (ErrMissingRecipe);
//   - the name the owner reads is not empty: the name is never guessed
//     (ErrInvalidName);
//   - the name of a product is taken inside the business: two products of a
//     business never share the name the owner reads (ErrDuplicateName);
//   - one recipe backs one product inside the business: the product of a
//     recipe is never a second one (ErrDuplicateRecipe).
//
// The product that is already in the book is the one that is answered, and
// the name is compared the way a person reads it: trimmed and without case.
//
// The identity of the product that comes into being is not set here: the
// storage generates it.
func TheProduct(own business.ID, held []Product, from recipe.ID, name string) (Product, error) {
	if from == 0 {
		return Product{}, fmt.Errorf("%w: the product names no recipe", ErrMissingRecipe)
	}

	trimmedName := strings.TrimSpace(name)
	if trimmedName == "" {
		return Product{}, fmt.Errorf("%w: the name of a product is not empty", ErrInvalidName)
	}

	for _, one := range held {
		if one.RecipeID == from {
			if sameName(one.Name, trimmedName) {
				return one, nil
			}

			return Product{}, fmt.Errorf("%w: the recipe %d backs the product %q",
				ErrDuplicateRecipe, from, one.Name)
		}

		if sameName(one.Name, trimmedName) {
			return Product{}, fmt.Errorf("%w: the product %q is the one of the recipe %d",
				ErrDuplicateName, one.Name, one.RecipeID)
		}
	}

	return Product{
		BusinessID: own,
		RecipeID:   from,
		Name:       trimmedName,
	}, nil
}

// OwnedBy states whether a business of that kind may hold a price list.
//
// The rule of the domain: the price list belongs to the business of the
// bakery, the one that sells the bread. The Personal Business of a person
// holds the money of that person, and not the price list of the bakery.
//
// The error is ErrWrongBusiness when the business is of another kind.
func OwnedBy(kind business.Kind) error {
	if kind != business.KindBusiness {
		return fmt.Errorf("%w: the kind of the business is %q, and the price list belongs to a business of its own",
			ErrWrongBusiness, kind)
	}

	return nil
}

// Price is the money of the product in a channel, with the day it was
// set.
//
// The price carries the channel it was set for from the first row: the
// discount of the wholesale never has to rebuild the history of the
// prices.
//
// The money of a price is whole pesos: the money of the book counts the
// pesos the person has.
type Price struct {
	// ID is the identity of the price. It is empty until the storage
	// writes the row.
	ID PriceID

	// BusinessID is the business that owns the price and that holds the
	// price list.
	BusinessID business.ID

	// ProductID is the product the price is of.
	ProductID ID

	// Channel is the channel the price was set for.
	Channel Channel

	// Amount is the money of the product in that channel, in whole pesos.
	Amount ledger.Amount

	// Day is the day the price was set.
	Day ledger.Date

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// NewPrice builds the price of a product for a channel.
//
// The rules of the domain hold here:
//
//   - the price names the product it is of (ErrMissingProduct);
//   - the price carries the channel it was set for: there is no price
//     without a channel and no default channel (ErrUnknownChannel);
//   - the money of the price is a positive number of whole pesos: a price
//     of zero pesos is not a price the owner charges (ErrInvalidPrice);
//   - the price carries the day it was set (ErrMissingDay).
func NewPrice(
	own business.ID,
	of ID,
	channel Channel,
	amount ledger.Amount,
	day ledger.Date,
) (Price, error) {
	if of == 0 {
		return Price{}, fmt.Errorf("%w: the price names no product", ErrMissingProduct)
	}

	if !channel.Valid() {
		return Price{}, fmt.Errorf("%w: %q", ErrUnknownChannel, channel)
	}

	if amount <= 0 {
		return Price{}, fmt.Errorf("%w: %d pesos", ErrInvalidPrice, amount)
	}

	if day.Time().IsZero() {
		return Price{}, fmt.Errorf("%w: the price carries no day", ErrMissingDay)
	}

	return Price{
		BusinessID: own,
		ProductID:  of,
		Channel:    channel,
		Amount:     amount,
		Day:        day,
	}, nil
}

// ThePriceOn answers the price that holds for a product and a channel on a
// day.
//
// The rule of the domain: the price that holds is the LAST one set on or
// before the day that is asked for. The rows that came before it are kept:
// the price list is a history, and nothing is rewritten when a price
// changes.
//
// Two prices of the same day are read in the order they were set: the last
// one that was set is the one that holds.
//
// The answer is false when the business set no price for that product and
// that channel on or before the day.
func ThePriceOn(held []Price, of ID, channel Channel, day ledger.Date) (Price, bool) {
	var found Price
	known := false

	for _, one := range held {
		if one.ProductID != of || one.Channel != channel {
			continue
		}

		if one.Day.After(day) {
			continue
		}

		if !known || laterThan(one, found) {
			found = one
			known = true
		}
	}

	return found, known
}

// laterThan states that one price was set after another one.
//
// The rule of the domain: the price that holds is the last one that was
// set, and the order of the set is the day first and the identity of the
// row after it.
func laterThan(one, other Price) bool {
	if one.Day.After(other.Day) {
		return true
	}

	if one.Day.Before(other.Day) {
		return false
	}

	return one.ID > other.ID
}

// Listed is one line of the price list: the product and the price that
// holds for it.
type Listed struct {
	// Product is the product the line is of.
	Product Product

	// Price is the price that holds for the product and the channel of
	// the line.
	Price Price
}

// ThePriceList answers the price list of the business on a day.
//
// The rule of the domain: the line of the list is the product and the
// channel, and it carries the price that holds on the day — the last one
// set on or before it. The product and the channel are optional: the zero
// identity and the empty channel answer the whole list.
//
// A product the business has not priced yet is not in the answer: the list
// is the price list, and the product without a price is not a line of it.
func ThePriceList(
	held []Price,
	products []Product,
	day ledger.Date,
	of ID,
	channel Channel,
) []Listed {
	list := make([]Listed, 0, len(products))

	for _, one := range products {
		if of != 0 && one.ID != of {
			continue
		}

		for _, candidate := range channels {
			if channel != "" && candidate != channel {
				continue
			}

			price, ok := ThePriceOn(held, one.ID, candidate, day)
			if !ok {
				continue
			}

			list = append(list, Listed{Product: one, Price: price})
		}
	}

	return list
}

// Named answers the products that carry that name.
//
// The rule of the domain: the name is compared the way a person reads it,
// trimmed and without case: "Pan de molde" and "pan de molde " are the
// same name.
//
// The name of a product is taken inside the business, and the answer
// carries the product that carries it: the book never guesses which one
// the owner meant.
func Named(products []Product, name string) []Product {
	key := strings.ToLower(strings.TrimSpace(name))
	if key == "" {
		return nil
	}

	found := make([]Product, 0, len(products))

	for _, one := range products {
		if strings.ToLower(strings.TrimSpace(one.Name)) == key {
			found = append(found, one)
		}
	}

	return found
}

// sameName states whether two names are the name a person reads.
//
// The rule of the domain: the name is compared trimmed and without case:
// "Pan de molde" and "pan de molde " are the same name.
func sameName(one, other string) bool {
	return strings.EqualFold(strings.TrimSpace(one), strings.TrimSpace(other))
}
