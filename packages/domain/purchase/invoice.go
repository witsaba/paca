// The invoice: the fact that comes with the purchase.
//
// The invoice is a fact of the purchase, and it is NOT money: the purchase
// already moved the money of the payment when the owner bought, and the
// invoice arrives later. The invoice says what the provider issued: its
// number, its day, its total and the tax that travels with it.
//
// The tax of an invoice is NEVER ASSUMED: it comes from the invoice. The
// invoice states the RATE it was issued with and the BASE that rate
// applies to, and the book derives the tax from the two of them. There is
// no default of nineteen percent and no default of zero, and the rate is
// never taken from the catalogue of the country: the rule of the tax
// authority and the advice of the professional of the owner are not read
// here.
//
// The electronic invoice is NEVER ASSUMED either: there is no integration
// with the tax authority and no field that pretends to be one. The
// reference of the invoice is a plain fact of the document the owner shows.
//
// The provider of an invoice is a PARTY: the farm, the store or the person
// the business buys from, and the party holds the role of the provider. A
// party that holds only the role of the client is refused as a provider, and
// a party may hold both roles.
//
// The number of an invoice is what identifies it, and it is unique inside
// the business that holds it.

const (
	// RateScale is the number of hundredths of a percent in a whole
	// percent.
	//
	// The rate is counted in hundredths because the rate of the tax
	// authority of the owner may not be a whole percent, and a rate that
	// is rounded away is a rate nobody charged.
	RateScale int64 = 100

	// MaxRate is the highest rate the book accepts: a hundred percent.
	MaxRate int64 = 100 * RateScale

	// rateDenominator is the number of hundredths of a percent in a whole
	// one: the rate of a tax is a share of the base, and the base is
	// multiplied by it.
	rateDenominator int64 = 100 * RateScale
)

// InvoiceID is the identity of an invoice.
//
// The number is generated by the database: it is the counter of the invoices
// and not a number of the person. The type exists so that an identifier
// never travels as a plain integer by accident.
type InvoiceID int64

// Rate is the rate of a tax.
//
// The rate is the one the invoice states, and the book never assumes one:
// there is no default of nineteen percent and no default of zero, and the
// catalogue of the country is never read here.
//
// The rate is counted in HUNDREDTHS of a percent: a rate of nineteen and a
// half is nineteen hundred and fifty. The money of the book counts whole
// pesos, and the tax of that rate is money of the book like every other
// one.
type Rate int64

// NewRate builds the rate of a tax from the percent the invoice states.
//
// The percent is the number a person reads: 19, 19.5, 0. The rate keeps
// the hundredths of it, and it never rounds them away.
//
// The error is ErrInvalidRate when the percent is not a rate: a rate is
// between zero and a hundred percent, and a rate outside of it is a number
// nobody can charge.
func NewRate(percent float64) (Rate, error) {
	if math.IsNaN(percent) || math.IsInf(percent, 0) {
		return 0, fmt.Errorf("%w: %v", ErrInvalidRate, percent)
	}

	return NewRateFromHundredths(int64(math.Round(percent * float64(RateScale))))
}

// NewRateFromHundredths builds the rate from the hundredths of a percent.
//
// The storage holds the rate in hundredths of a percent, and the row never
// decides what a rate is: the domain reads it back through this
// constructor.
//
// The error is ErrInvalidRate when the rate is not between zero and a
// hundred percent.
func NewRateFromHundredths(hundredths int64) (Rate, error) {
	if hundredths < 0 || hundredths > MaxRate {
		return 0, fmt.Errorf("%w: %d hundredths of a percent", ErrInvalidRate, hundredths)
	}

	return Rate(hundredths), nil
}

// Hundredths answers the rate in hundredths of a percent.
func (r Rate) Hundredths() int64 {
	return int64(r)
}

// Percent answers the rate in percent, the way a person reads it.
func (r Rate) Percent() float64 {
	return float64(r) / float64(RateScale)
}

// String answers the rate the way a person reads it: 19, 19.5, 0.
func (r Rate) String() string {
	return strconv.FormatFloat(r.Percent(), 'f', -1, 64)
}

// TheTax answers the tax of a base at that rate.
//
// The rule of the book: the tax is the rate applied to the base, and it is
// rounded to the NEAREST whole peso, and a half peso goes UP. The money of
// the book counts whole pesos, and the tax of an invoice is money of the
// book like every other one.
//
// A base of fifty pesos at nineteen percent is nine pesos and a half, and
// the tax of that invoice is ten pesos: the half peso goes up, and the
// invoice that does not add up is refused.
//
// The rate is never assumed: the tax is the one the invoice states.
func TheTax(base ledger.Amount, rate Rate) ledger.Amount {
	if base <= 0 || rate <= 0 {
		return 0
	}

	money := int64(base) * int64(rate)

	return ledger.Amount((money + rateDenominator/2) / rateDenominator)
}

// Invoice is the fact of what the provider issued with the purchase.
//
// The invoice moves NO money: the purchase moved the money of the payment
// when the owner bought, and the invoice arrives later. The invoice is
// written against the purchase it came from, and the purchase points at
// the invoice.
//
// The money of an invoice is whole pesos: the book counts the pesos the
// person has.
type Invoice struct {
	// ID is the identity of the invoice. It is empty until the storage
	// writes the row.
	ID InvoiceID

	// BusinessID is the business that bought and that holds the invoice.
	BusinessID business.ID

	// ProviderID is the party that issued the invoice: the farm, the
	// store or the person the business buys from.
	ProviderID party.ID

	// PurchaseID is the purchase the invoice came from. The purchase
	// points at the invoice, and the invoice names the purchase.
	PurchaseID ID

	// Number is the number the invoice carries. It is what identifies it
	// inside the business that holds it.
	Number string

	// Day is the day the invoice was issued.
	Day ledger.Date

	// Base is the money the tax applies to, in whole pesos.
	Base ledger.Amount

	// Rate is the rate the invoice was issued with. It is the rate the
	// invoice states, and the book never assumes one.
	Rate Rate

	// Tax is the tax of the base at the rate, in whole pesos. It is
	// DERIVED by the book from the base and the rate of the invoice.
	Tax ledger.Amount

	// Total is the money of the whole invoice, in whole pesos. It is the
	// base plus the tax, and an invoice that does not add up is refused.
	Total ledger.Amount

	// Reference is the reference of the document the owner shows. It is a
	// plain fact of the invoice, and it is never the mark of an
	// electronic invoice: the repository never assumes one.
	Reference string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// InvoiceDefinition is what the agent read of the invoice.
//
// It is the candidate the owner showed, and the domain decides what may
// enter the book of the business.
type InvoiceDefinition struct {
	// PurchaseID is the purchase the invoice came from.
	PurchaseID ID

	// Number is the number the invoice carries.
	Number string

	// Day is the day the invoice was issued.
	Day ledger.Date

	// Base is the money the tax applies to, in whole pesos.
	Base ledger.Amount

	// Rate is the rate the invoice was issued with.
	Rate Rate

	// Total is the money of the whole invoice, in whole pesos.
	Total ledger.Amount

	// Reference is the reference of the document the owner shows. It is
	// optional.
	Reference string
}

// NewInvoice builds the invoice of the purchase it came from.
//
// The rules of the domain hold here:
//
//   - the invoice names the provider that issued it: the provider is a
//     party, and it holds the role of the provider. A party that holds
//     only the role of the client is refused (ErrNotAProvider);
//   - the provider is a party of the business that bought: the invoice of
//     one business is never the invoice of another one
//     (ErrInvoiceOfAnotherBusiness);
//   - the invoice names the purchase it came from: an invoice without a
//     purchase is a fact of nobody (ErrMissingPurchase);
//   - the invoice carries its number (ErrMissingInvoiceNumber) and its
//     day (ErrMissingInvoiceDay);
//   - the money of the invoice is not negative (ErrInvalidInvoiceMoney);
//   - the total of the invoice is the base plus the tax the rate gives
//     it: an invoice that does not add up is never read as an invoice
//     (ErrInvoiceDoesNotAddUp).
//
// The tax is DERIVED by the book from the base and the rate the invoice
// states, and it is rounded to the nearest whole peso with a half peso
// going up.
func NewInvoice(
	own business.ID,
	provider party.Party,
	definition InvoiceDefinition,
) (Invoice, error) {
	if provider.ID == 0 {
		return Invoice{}, fmt.Errorf("%w: the invoice names no provider", ErrMissingProvider)
	}

	if !provider.Is(party.RoleProvider) {
		return Invoice{}, fmt.Errorf("%w: the party %q holds %v", ErrNotAProvider, provider.Name, provider.Roles)
	}

	if provider.BusinessID != own {
		return Invoice{}, fmt.Errorf("%w: the provider %q is of the business %d and the invoice is of the business %d",
			ErrInvoiceOfAnotherBusiness, provider.Name, provider.BusinessID, own)
	}

	if definition.PurchaseID == 0 {
		return Invoice{}, fmt.Errorf("%w: the invoice names no purchase", ErrMissingPurchase)
	}

	number := strings.TrimSpace(definition.Number)
	if number == "" {
		return Invoice{}, fmt.Errorf("%w: the number of the invoice is not empty", ErrMissingInvoiceNumber)
	}

	if definition.Day.Time().IsZero() {
		return Invoice{}, fmt.Errorf("%w: the invoice carries no day", ErrMissingInvoiceDay)
	}

	if definition.Base < 0 || definition.Total < 0 {
		return Invoice{}, fmt.Errorf("%w: the base is %d and the total is %d",
			ErrInvalidInvoiceMoney, definition.Base, definition.Total)
	}

	tax := TheTax(definition.Base, definition.Rate)
	if definition.Total != definition.Base+tax {
		return Invoice{}, fmt.Errorf("%w: the base is %d and the tax is %d and the total is %d",
			ErrInvoiceDoesNotAddUp, definition.Base, tax, definition.Total)
	}
	return Invoice{
		BusinessID: own,
		ProviderID: provider.ID,
		PurchaseID: definition.PurchaseID,
		Number:     number,
		Day:        definition.Day,
		Base:       definition.Base,
		Rate:       definition.Rate,
		Tax:        tax,
		Total:      definition.Total,
		Reference:  strings.TrimSpace(definition.Reference),
	}, nil
}

// InvoiceFacts are the facts of an invoice that the storage holds.
//
// They are the row read back: the domain reads them through its own
// constructor, and the row never decides what an invoice is.
type InvoiceFacts struct {
	// ID is the identity of the invoice.
	ID InvoiceID

	// BusinessID is the business that holds the invoice.
	BusinessID business.ID

	// ProviderID is the party that issued the invoice.
	ProviderID party.ID

	// PurchaseID is the purchase the invoice came from.
	PurchaseID ID

	// Number is the number the invoice carries.
	Number string

	// Day is the day the invoice was issued.
	Day ledger.Date

	// Base is the money the tax applies to, in whole pesos.
	Base ledger.Amount

	// Rate is the rate the invoice was issued with.
	Rate Rate

	// Tax is the tax of the base at the rate, in whole pesos.
	Tax ledger.Amount

	// Total is the money of the whole invoice, in whole pesos.
	Total ledger.Amount

	// Reference is the reference of the document the owner shows.
	Reference string
}

// NewInvoiceFromFacts builds the invoice the storage holds.
//
// The rule of the domain holds here too: the tax of the invoice is the tax
// of the base at the rate, and the total is the base plus the tax. An
// invoice that does not add up is never read as an invoice, and the row
// that another writer broke is refused with the same error.
//
// The error is ErrInvalidInvoiceMoney when the money of the invoice is
// negative, and ErrInvoiceDoesNotAddUp when the invoice does not add up.
func NewInvoiceFromFacts(facts InvoiceFacts) (Invoice, error) {
	number := strings.TrimSpace(facts.Number)
	if number == "" {
		return Invoice{}, fmt.Errorf("%w: the number of the invoice is not empty", ErrMissingInvoiceNumber)
	}

	if facts.Day.Time().IsZero() {
		return Invoice{}, fmt.Errorf("%w: the invoice carries no day", ErrMissingInvoiceDay)
	}

	if facts.PurchaseID == 0 {
		return Invoice{}, fmt.Errorf("%w: the invoice names no purchase", ErrMissingPurchase)
	}

	invoice := Invoice{
		ID:         facts.ID,
		BusinessID: facts.BusinessID,
		ProviderID: facts.ProviderID,
		PurchaseID: facts.PurchaseID,
		Number:     number,
		Day:        facts.Day,
		Base:       facts.Base,
		Rate:       facts.Rate,
		Tax:        facts.Tax,
		Total:      facts.Total,
		Reference:  strings.TrimSpace(facts.Reference),
	}

	if err := invoice.holdsTogether(); err != nil {
		return Invoice{}, err
	}

	return invoice, nil
}

// holdsTogether states that the money of the invoice adds up.
//
// The rule of the domain: the tax of the invoice is the tax of the base at
// the rate, and the total is the base plus the tax. An invoice that does
// not add up is never read as an invoice.
func (i Invoice) holdsTogether() error {
	if i.Base < 0 || i.Tax < 0 || i.Total < 0 {
		return fmt.Errorf("%w: the base is %d, the tax is %d and the total is %d",
			ErrInvalidInvoiceMoney, i.Base, i.Tax, i.Total)
	}

	tax := TheTax(i.Base, i.Rate)
	if i.Tax != tax {
		return fmt.Errorf("%w: the tax is %d and the rate of the invoice gives %d",
			ErrInvoiceDoesNotAddUp, i.Tax, tax)
	}

	if i.Total != i.Base+i.Tax {
		return fmt.Errorf("%w: the base is %d, the tax is %d and the total is %d",
			ErrInvoiceDoesNotAddUp, i.Base, i.Tax, i.Total)
	}

	return nil
}

// AttachesTo states that the invoice may be attached to that purchase.
//
// The rule of the domain: the purchase points at the invoice it came from,
// and a purchase of a business cannot point at an invoice of another
// business. The error is ErrInvoiceOfAnotherBusiness when the purchase
// belongs to another business.
func (i Invoice) AttachesTo(bought Purchase) error {
	if bought.ID == 0 {
		return fmt.Errorf("%w: the invoice names no purchase", ErrMissingPurchase)
	}

	if bought.BusinessID != i.BusinessID {
		return fmt.Errorf("%w: the purchase %d is of the business %d and the invoice is of the business %d",
			ErrInvoiceOfAnotherBusiness, bought.ID, bought.BusinessID, i.BusinessID)
	}

	return nil
}

// UniqueInvoiceNumber states that the number of the invoice is free inside
// the business that holds it.
//
// The rule of the domain: the number of an invoice is what identifies it,
// and it is unique inside the business that holds it. The error is
// ErrDuplicateInvoiceNumber when the business already holds that number.
func UniqueInvoiceNumber(held []Invoice, candidate Invoice) error {
	for _, one := range held {
		if one.ID == candidate.ID {
			continue
		}

		if one.BusinessID != candidate.BusinessID {
			continue
		}

		if one.Number == candidate.Number {
			return fmt.Errorf("%w: the invoice %q is already in the business %d",
				ErrDuplicateInvoiceNumber, candidate.Number, candidate.BusinessID)
		}
	}

	return nil
}
