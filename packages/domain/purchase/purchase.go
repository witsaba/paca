// Package purchase holds the model of the draft of a purchase: the
// candidate that the agent proposes from what the owner said, and the rules
// of what may enter the book.
//
// A draft is a proposal, not a fact. It is kept by the business that owns
// it, with its state, its revision and the sentence it came from, and it
// waits for the yes of the owner before anything is written in the book.
// The transport of the MCP server is stateless, and a candidate that lives
// only in the context of the model is a candidate that can be paraphrased,
// lost or silently changed between the proposal and the yes.
//
// The three parts of the answer of the agent come from here: what the draft
// understood, what it still needs and what it was not sure about. The
// fields the owner said and the fields Paca filled are never mixed, and the
// money is never one of the fields Paca fills.
//
// The package holds the purchase as well: the fact of what the business
// bought, with its lines, with the sentence the owner said and with the
// word she used to confirm it. The confirmation is a rule of the domain: it
// refuses the draft that expired, the draft that changed under the eyes of
// the owner and the draft that still needs the money of one of its lines.
//
// The package imports nothing but the standard library, the model of the
// business that owns the draft, the model of the account of its book and
// the model of the money of the book.
package purchase

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ledger"
)

// DraftID is the identity of a draft.
//
// The number is generated by the database: it is the counter of the drafts
// and not a number of the person. The type exists so that an identifier
// never travels as a plain integer by accident.
type DraftID int64

// State is the state of a draft.
//
// A draft is proposed, and it waits: the states it ends in - confirmed,
// cancelled and expired - come with the increment that writes the purchase
// and the one that cancels a draft.
type State string

const (
	// StateProposed is the state of a draft that waits for the yes of the
	// owner.
	StateProposed State = "proposed"

	// StateConfirmed is the state of a draft the owner confirmed: the
	// purchase is written, and the draft never waits again.
	StateConfirmed State = "confirmed"
)

// String returns the name of the state.
//
// It is the name the storage holds, with no translation in between.
func (s State) String() string {
	return string(s)
}

// DraftLifetimeDays is the lifetime of a draft, in days.
//
// The price of a market does not wait: a draft that was neither confirmed
// nor cancelled in seven days expires.
const DraftLifetimeDays = 7

// Draft is the candidate the agent proposed from what the owner said.
//
// The draft is the fact of the business and not of the conversation: it is
// stored, and the confirmation of the owner writes the purchase out of it.
type Draft struct {
	// ID is the identity of the draft. It is empty until the storage
	// writes the row.
	ID DraftID

	// BusinessID is the business that owns the draft.
	BusinessID business.ID

	// State is the state of the draft.
	State State

	// Revision is the number of the revision of the draft. It grows with
	// every amendment, and the confirmation of the owner carries the
	// revision she saw.
	Revision int

	// Utterance is the sentence of the owner, verbatim. It is kept with the
	// draft, so the entry can be audited and derived again.
	Utterance string

	// Lines are the lines the agent read.
	Lines []Line

	// Missing is what the draft still needs: the price of a line the owner
	// did not name.
	Missing []string

	// Ambiguous is what the agent was not sure about, with the options it
	// offers.
	Ambiguous []Ambiguity

	// Inferred is what Paca filled by herself.
	Inferred []string

	// Day is the day of the purchase.
	Day ledger.Date

	// Market is the market the purchase happened in. It is empty when the
	// owner named none.
	Market string

	// Invoice is the invoice of the purchase. It is empty when the owner
	// named none.
	Invoice string

	// ProposedOn is the day the draft was proposed.
	ProposedOn ledger.Date

	// ExpiresOn is the day the draft expires.
	ExpiresOn ledger.Date

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time

	// UpdatedAt is the moment the row was last written. The storage filled
	// it on insert; whoever updates a row is responsible for it after that.
	UpdatedAt time.Time
}

// Candidate is what the agent read from the sentence of the owner: the
// lines of the purchase, the day, the market, the invoice and the
// ambiguities it found.
//
// The day is the day the owner named: the zero day means she named none,
// and Paca fills the day of today.
type Candidate struct {
	// Lines are the lines the agent read.
	Lines []Line

	// Day is the day the owner named. The zero day means she named none.
	Day ledger.Date

	// Market is the market the owner named. It is empty when she named
	// none.
	Market string

	// Invoice is the invoice the owner named. It is empty when she named
	// none.
	Invoice string

	// Ambiguities are the names the agent was not sure about.
	Ambiguities []Ambiguity
}

// Ambiguity is a name the agent was not sure about, with the options it
// offers.
//
// Paca never asks an open question when it can name the options: it offers
// the two or three candidates it found, and the owner answers with one
// word.
type Ambiguity struct {
	// Name is the name as the owner said it.
	Name string

	// Options are the candidates the agent found.
	Options []string
}

// NewAmbiguity builds an ambiguity of a draft.
//
// The name may not be empty: the owner would not know what she is being
// asked about. The ambiguity carries at least one option: an ambiguity
// without options is an open question, and Paca never asks one.
func NewAmbiguity(name string, options []string) (Ambiguity, error) {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return Ambiguity{}, fmt.Errorf("%w: the name of an ambiguity is not empty", ErrInvalidName)
	}

	if len(options) == 0 {
		return Ambiguity{}, fmt.Errorf("%w: the ambiguity %q carries no option", ErrNoOptions, trimmed)
	}

	return Ambiguity{Name: trimmed, Options: options}, nil
}

// NewDraft builds a draft of a purchase.
//
// The sentence of the owner is required: the draft is the reading of what
// she said, and a draft without the sentence cannot be audited nor derived
// again.
//
// The lines are required: a proposal of nothing is not a proposal.
//
// The day of the purchase is optional, and it is the day of today when the
// owner named none: the day, the currency and the business are the three
// things Paca may fill by herself. The market and the invoice are
// optional, and they stay absent when the owner named none.
//
// The draft expires seven days after the day it was proposed: the price of
// a market does not wait.
func NewDraft(
	own business.ID,
	utterance string,
	candidate Candidate,
	proposedOn ledger.Date,
) (Draft, error) {
	trimmed := strings.TrimSpace(utterance)
	if trimmed == "" {
		return Draft{}, fmt.Errorf("%w: the sentence of the owner is not empty", ErrMissingUtterance)
	}

	if len(candidate.Lines) == 0 {
		return Draft{}, fmt.Errorf("%w: the draft proposes nothing", ErrNoLines)
	}

	day := candidate.Day
	inferred := []string{}
	if day.Time().IsZero() {
		day = proposedOn
		inferred = append(inferred, "the day of the purchase is the day of today")
	}

	return Draft{
		BusinessID: own,
		State:      StateProposed,
		Revision:   1,
		Utterance:  trimmed,
		Lines:      candidate.Lines,
		Missing:    missingOf(candidate.Lines),
		Ambiguous:  candidate.Ambiguities,
		Inferred:   inferred,
		Day:        day,
		Market:     strings.TrimSpace(candidate.Market),
		Invoice:    strings.TrimSpace(candidate.Invoice),
		ProposedOn: proposedOn,
		ExpiresOn:  ledger.NewDate(proposedOn.Time().AddDate(0, 0, DraftLifetimeDays)),
	}, nil
}

// Amend applies a new reading of the sentence to a draft.
//
// The sentence the owner said the first time is kept: the draft is audited
// with the words she used. The lines, the day, the market and the invoice
// are the ones of the new reading, and the revision grows by one.
//
// The day of the draft is kept when the new reading names none, and so is
// the list of the things Paca filled: the owner corrected the price, not
// the day.
func Amend(draft Draft, candidate Candidate) (Draft, error) {
	if len(candidate.Lines) == 0 {
		return Draft{}, fmt.Errorf("%w: the amendment proposes nothing", ErrNoLines)
	}

	day := candidate.Day
	inferred := []string{}
	if day.Time().IsZero() {
		day = draft.Day
		inferred = append(inferred, draft.Inferred...)
	}

	return Draft{
		ID:         draft.ID,
		BusinessID: draft.BusinessID,
		State:      StateProposed,
		Revision:   draft.Revision + 1,
		Utterance:  draft.Utterance,
		Lines:      candidate.Lines,
		Missing:    missingOf(candidate.Lines),
		Ambiguous:  candidate.Ambiguities,
		Inferred:   inferred,
		Day:        day,
		Market:     strings.TrimSpace(candidate.Market),
		Invoice:    strings.TrimSpace(candidate.Invoice),
		ProposedOn: draft.ProposedOn,
		ExpiresOn:  draft.ExpiresOn,
	}, nil
}

// missingOf answers what the draft still needs: the price of every line the
// owner did not price.
//
// The money is never inferred, so a line without a price is a question the
// draft asks.
func missingOf(lines []Line) []string {
	missing := make([]string, 0, len(lines))

	for _, one := range lines {
		if !one.Price.Present() {
			missing = append(missing, "the price of "+one.Name)
		}
	}

	return missing
}
