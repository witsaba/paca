package purchase

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ingredient"
	"github.com/witsaba/paca/packages/domain/ledger"
)

// The reference price: what the market was seen at, where it was read and
// the day it was read.
//
// A reference is NEVER the price of the ingredient: the price the owner pays
// exists only in the market of her town and only in her mouth on the day.
// The research of Paca returns public references with their source and
// their day, and the reference is labelled as one, so that no later
// analysis may read it as the price of the ingredient.
//
// The reference lives here, next to the price it is a reference of: it is a
// price fact of the business and not a field of the ingredient.

// ReferenceKind is the name the person reads in her book: a reference is a
// reference, and never the price of the ingredient.
//
// The kind belongs to the domain: the answer of the tool carries it, and the
// description of the tool reads it.
const ReferenceKind = "reference"

// ReferenceID is the identity of a reference.
//
// The number is generated by the database: it is the counter of the
// references and not a number of the person. The type exists so that an
// identifier never travels as a plain integer by accident.
type ReferenceID int64

// Reference is the price of a market that Paca researched.
//
// It carries the ingredient it is about, the price that was seen, the unit
// of that price, the market where it was seen, the place it was read and
// the day it was read.
//
// The money of the book counts whole pesos: a reference is a price fact of
// the business, and it is counted like every other one.
type Reference struct {
	// ID is the identity of the reference. It is empty until the storage
	// writes the row.
	ID ReferenceID

	// BusinessID is the business the reference belongs to.
	BusinessID business.ID

	// IngredientID is the identity of the ingredient of the catalog the
	// reference is about.
	IngredientID ingredient.ID

	// Price is the price that was seen, in whole pesos. It is the price of
	// the market and never the price of the ingredient.
	Price ledger.Amount

	// Unit is the unit of that price: the kilo, the package, the piece.
	Unit string

	// Market is the market where the price was seen. It is empty when the
	// research named none.
	Market string

	// Source is the place the price was read. It is never empty: a price
	// without a source is a price nobody can check.
	Source string

	// SeenOn is the day the price was seen.
	SeenOn ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word the owner used to confirm the reference.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// Label answers the name the person reads in her book.
//
// It is always the name of a reference: a reference never answers as the
// price of the ingredient, and the rule lives in the domain so that no
// caller may read it another way.
func (r Reference) Label() string {
	return ReferenceKind
}

// ReferenceDefinition is what the agent read about a reference.
//
// It is the candidate the research produced, and the domain decides what may
// enter the book of the business.
type ReferenceDefinition struct {
	// IngredientID is the identity of the ingredient of the catalog the
	// reference is about.
	IngredientID ingredient.ID

	// Price is the price that was seen, in whole pesos.
	Price ledger.Amount

	// Unit is the unit of that price.
	Unit string

	// Market is the market where the price was seen. It is empty when the
	// research named none.
	Market string

	// Source is the place the price was read.
	Source string

	// SeenOn is the day the price was seen.
	SeenOn ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word the owner used to confirm it.
	ConfirmedWith string
}

// NewReference builds the reference of a business.
//
// The rules of the domain hold here:
//
//   - the reference names an ingredient of the catalog: a reference of
//     nothing is a price of nobody;
//   - the price is a price: it is positive, and it is whole pesos;
//   - the price carries its unit: a price without a unit is a number nobody
//     can compare with anything;
//   - the reference carries its source: a price without a source is a price
//     nobody can check;
//   - the reference carries the day it was seen: a price that never was is
//     not a price;
//   - the reference carries the word of the owner: it is written with her
//     confirmation, the way the purchase is written.
//
// The market is optional: it is there when the research named one, and it is
// absent when it named none.
func NewReference(own business.ID, definition ReferenceDefinition) (Reference, error) {
	if definition.IngredientID == 0 {
		return Reference{}, fmt.Errorf("%w: the reference names nothing of the catalog", ErrMissingIngredient)
	}

	if definition.Price <= 0 {
		return Reference{}, fmt.Errorf("%w: the price of the reference is %d",
			ErrInvalidReferencePrice, definition.Price)
	}

	unit := strings.TrimSpace(definition.Unit)
	if unit == "" {
		return Reference{}, fmt.Errorf("%w: the price of the reference carries its unit", ErrMissingReferenceUnit)
	}

	source := strings.TrimSpace(definition.Source)
	if source == "" {
		return Reference{}, fmt.Errorf("%w: the reference carries the place the price was read", ErrMissingSource)
	}

	if definition.SeenOn.Time().IsZero() {
		return Reference{}, fmt.Errorf("%w: the reference carries the day the price was seen", ErrMissingDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Reference{}, fmt.Errorf("%w: the reference carries no word of the owner", ErrMissingConfirmation)
	}

	return Reference{
		BusinessID:    own,
		IngredientID:  definition.IngredientID,
		Price:         definition.Price,
		Unit:          unit,
		Market:        strings.TrimSpace(definition.Market),
		Source:        source,
		SeenOn:        definition.SeenOn,
		Utterance:     strings.TrimSpace(definition.Utterance),
		ConfirmedWith: word,
	}, nil
}
