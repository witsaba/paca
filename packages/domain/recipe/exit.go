// The exit of the book of the bread: the consumption of the owner and the
// donation.
//
// The four exits of the book are the sale, the waste, the consumption and
// the donation. The sale moves the money in, the waste carries the reason
// of what the bakery lost, and the consumption and the donation are the two
// exits that move no money IN: nobody paid for the bread the owner consumed
// or for the bread the bakery gave away. What they do is release the cost
// of the units that left the book, and that is all.
//
// The cost of the units that left is derived, never typed: it is the money
// of the production the unit came out of, divided by the units that
// production made. The derivation is the one of the waste and of the sale,
// and it is never written a second time.
//
// The tax treatment of an exit is never decided by the book: the movement
// is recorded and the question is named, and the question waits for the
// professional of the taxes of the owner. There is no rate that the book
// assumes and no default that it hides.
//
// The donation is a social expense of the business: it lands in the account
// of the donation, the account the book of a business opens for what it
// gives away. The consumption of the owner releases the cost like a sale
// does: the cost of the units leaves the inventory and it lands in the
// account of the cost of the sales.

// ExitID is the identity of an exit of the book.
//
// The number is generated by the database. The type exists so that an
// identifier never travels as a plain integer by accident.
type ExitID int64

// ExitKind is the kind of an exit of the book.
//
// The exits of the bakery are the consumption of the owner and the
// donation, and the book never guesses one of them.
type ExitKind string

const (
	// ExitConsumption is the exit of the units the owner consumed.
	ExitConsumption ExitKind = "consumption"

	// ExitDonation is the exit of the units the bakery gave away.
	ExitDonation ExitKind = "donation"
)

// theKindsOfTheExit holds the kinds of the exit, in the order they are
// presented.
var theKindsOfTheExit = []ExitKind{
	ExitConsumption,
	ExitDonation,
}

// theSpokenKinds holds the names the owner and the agent say for the kinds
// of the exit.
//
// The names are read the way a person reads them, and the answer is the
// kind the book knows: the storage and the protocol carry the two names of
// the kinds.
var theSpokenKinds = map[string]ExitKind{
	"consumption": ExitConsumption,
	"consumo":     ExitConsumption,
	"consumido":   ExitConsumption,
	"donation":    ExitDonation,
	"donacion":    ExitDonation,
	"donación":    ExitDonation,
	"donado":      ExitDonation,
	"regalo":      ExitDonation,
}

// AllExitKinds returns the kinds of the exit, in the order they are
// presented.
//
// The vocabulary belongs to the domain: the description of the tool reads
// it, and the check of the table holds the same rule as a defense in
// depth.
func AllExitKinds() []ExitKind {
	all := make([]ExitKind, len(theKindsOfTheExit))
	copy(all, theKindsOfTheExit)

	return all
}

// Valid reports whether the kind is one of the kinds of the book.
func (k ExitKind) Valid() bool {
	for _, one := range theKindsOfTheExit {
		if one == k {
			return true
		}
	}

	return false
}

// String returns the name of the kind.
//
// It is the name the storage and the protocol carry, with no translation in
// between.
func (k ExitKind) String() string {
	return string(k)
}

// ParseExitKind answers the kind of the exit the owner named.
//
// The name is read the way a person reads it: trimmed, and without case.
// The answer is the kind the book knows, never the way it was said.
//
// The error is ErrUnknownExitKind when the name is not one of the two kinds
// of the book: the exits of the bakery are the consumption of the owner and
// the donation, and no other one is guessed.
func ParseExitKind(spoken string) (ExitKind, error) {
	key := strings.ToLower(strings.TrimSpace(spoken))
	if key == "" {
		return "", fmt.Errorf("%w: the kind of the exit is not empty", ErrUnknownExitKind)
	}

	kind, known := theSpokenKinds[key]
	if !known {
		return "", fmt.Errorf("%w: %q", ErrUnknownExitKind, spoken)
	}

	return kind, nil
}

// TaxTreatment is the tax treatment of an exit of the book.
//
// The book decides no tax treatment of its own: the treatment of an exit
// is a question for the professional of the taxes of the owner, and the exit
// carries it while it waits.
type TaxTreatment string

const (
	// TaxPendingTheProfessional is the tax treatment of an exit whose
	// question nobody answered: the movement is recorded and the question
	// waits for the professional of the taxes of the owner.
	TaxPendingTheProfessional TaxTreatment = "pending_the_professional"
)

// Valid reports whether the treatment is one of the treatments of the book.
func (t TaxTreatment) Valid() bool {
	return t == TaxPendingTheProfessional
}

// String returns the name of the treatment.
//
// It is the name the storage and the protocol carry, with no translation in
// between.
func (t TaxTreatment) String() string {
	return string(t)
}

// The questions of the taxes.
//
// The question is named by the book and kept with the exit: the owner asked
// whether the business pays the tax of what she consumed or discounts it
// as a loss, and the question waits for the professional of the taxes.
const (
	// theQuestionOfTheConsumption is the question of the taxes of the
	// consumption of the owner.
	theQuestionOfTheConsumption = "El tratamiento tributario del consumo del dueño está pendiente del " +
		"profesional de los impuestos: PACA no decide si el negocio paga el impuesto de lo que " +
		"consumió o lo descuenta como pérdida."

	// theQuestionOfTheDonation is the question of the taxes of the
	// donation.
	theQuestionOfTheDonation = "El tratamiento tributario de la donación está pendiente del profesional " +
		"de los impuestos: PACA no decide si la donación es un gasto deducible o una pérdida."
)

// theQuestionOfTheTaxes answers the question of the taxes of the kind of
// the exit.
//
// The rule of the domain: the book decides no tax treatment, and every
// exit names the question it waits for. The question is never empty and it
// never assumes a rate.
func theQuestionOfTheTaxes(kind ExitKind) string {
	if kind == ExitDonation {
		return theQuestionOfTheDonation
	}

	return theQuestionOfTheConsumption
}

// ExitedUnit is a unit of a production that an exit took out of the book.
//
// The unit carries the production it came out of: the cost of the exit is
// the money of that production, and the analysis of the exit reads it from
// here.
type ExitedUnit struct {
	// UnitID is the identity of the unit that left the book.
	UnitID UnitID

	// ProductionID is the production the unit came out of.
	ProductionID ProductionID

	// Position is the order the unit was made in.
	Position int

	// Grams is the weight of the unit.
	Grams float64

	// ExpiresOn is the day the unit expires on.
	ExpiresOn ledger.Date
}

// Exit is what the bakery gave away or what the owner consumed.
//
// It carries the kind of the exit, the product, the quantity, the unit, the
// day it happened, the word of the owner and the cost the exit released.
// The units that left the book travel with it, and so does the question of
// the taxes that waits for the professional of the taxes of the owner.
type Exit struct {
	// ID is the identity of the exit. It is empty until the storage
	// writes the row.
	ID ExitID

	// BusinessID is the business that owns the exit.
	BusinessID business.ID

	// Kind is the kind of the exit: the consumption of the owner or the
	// donation.
	Kind ExitKind

	// RecipeID is the product the exit is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product. It is the
	// name of the recipe, and the recipe is the owner of it.
	RecipeName string

	// Day is the day the exit happened.
	Day ledger.Date

	// Quantity is how many units of the product the exit took.
	Quantity float64

	// Unit is the unit of that quantity: the exits of the bakery count
	// the units they took.
	Unit string

	// Cost is the cost of the units that left the book, in whole pesos:
	// the cost the exit released.
	Cost ledger.Amount

	// TaxTreatment is the tax treatment of the exit: it waits for the
	// professional of the taxes of the owner.
	TaxTreatment TaxTreatment

	// TaxQuestion is the question of the taxes the exit waits for.
	TaxQuestion string

	// Units are the units of the production that left the book, in the
	// order they expire: the one that expires first is the first one.
	Units []ExitedUnit

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the exit.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// ExitDefinition is what the owner said about the exit.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type ExitDefinition struct {
	// RecipeID is the product the exit is of. It is zero when the owner
	// names the product with its name.
	RecipeID ID

	// RecipeName is the name the owner reads of the product she consumed
	// or gave away. It is empty when she names the product with its
	// identity.
	RecipeName string

	// Kind is the kind of the exit: the consumption of the owner or the
	// donation.
	Kind ExitKind

	// Quantity is how many units of the product the exit took.
	Quantity float64

	// Unit is the unit of that quantity. It is empty when the owner named
	// none, and the exit counts the units it took then.
	Unit string

	// Day is the day the exit happened.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word she used to confirm the exit.
	ConfirmedWith string
}

// ExitFact is what the book keeps of an exit.
//
// The fact carries what the owner said and what the book derived: the
// units that left the book, the cost they were worth and the question of
// the taxes that waits for the professional of the taxes of the owner.
type ExitFact struct {
	// RecipeID is the product the exit is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product.
	RecipeName string

	// Kind is the kind of the exit.
	Kind ExitKind

	// Day is the day the exit happened.
	Day ledger.Date

	// Quantity is how many units of the product the exit took.
	Quantity float64

	// Unit is the unit of that quantity.
	Unit string

	// Cost is the cost of the units that left the book, in whole pesos.
	Cost ledger.Amount

	// TaxTreatment is the tax treatment of the exit.
	TaxTreatment TaxTreatment

	// TaxQuestion is the question of the taxes the exit waits for.
	TaxQuestion string

	// Units are the units of the production that left the book.
	Units []ExitedUnit

	// Utterance is the sentence of the owner, verbatim.
	Utterance string

	// ConfirmedWith is the word she used to confirm the exit.
	ConfirmedWith string
}

// ExitOf builds the exit the owner confirmed.
//
// The rules of the domain:
//
//   - the exit belongs to a business and names the product it took: the
//     name of a product is not unique inside the business, and a name that
//     more than one product carries is refused, because the book never
//     guesses which product she consumed or gave away;
//   - the kind of the exit is one of the two of the book: the exits of the
//     bakery are the consumption of the owner and the donation, and no
//     other one is guessed;
//   - the quantity is positive and whole: the exits of the bakery count
//     the units they took, and the book never splits a unit;
//   - the unit is the unit of a piece: the book never converts a weight
//     into a number of units;
//   - the exit carries the day it happened and the word of the owner: the
//     exit is written with her confirmation, the way the production, the
//     waste and the sale are written;
//   - the units that leave the book are the units of the product that are
//     still in it, in the order they expire: the one that expires first is
//     the first one. The sale is the only exit that refuses the unit that
//     expired: the bread that expired is still bread for the owner and for
//     the one she gives it to;
//   - the cost of the exit is the money of the units that left: the money
//     of the production they came out of, divided by the units that
//     production made. The money of the book counts whole pesos;
//   - the tax treatment of the exit waits for the professional of the
//     taxes of the owner: the movement is recorded and the question is
//     named, and the book never assumes a rate.
func ExitOf(
	own business.ID,
	productions []Production,
	held []ExpiringUnit,
	definition ExitDefinition,
) (Exit, error) {
	if own <= 0 {
		return Exit{}, fmt.Errorf("%w: the exit is of the business %d",
			ErrMissingBusiness, own)
	}

	if !definition.Kind.Valid() {
		return Exit{}, fmt.Errorf("%w: the kind of the exit is %q",
			ErrUnknownExitKind, definition.Kind)
	}

	recipeID, err := theProductOfTheBook(productions, definition.RecipeID, definition.RecipeName,
		definition.Kind.String())
	if err != nil {
		return Exit{}, err
	}

	if definition.Quantity <= 0 {
		return Exit{}, fmt.Errorf("%w: the exit carries %v units",
			ErrInvalidExitQuantity, definition.Quantity)
	}

	if definition.Quantity != math.Trunc(definition.Quantity) {
		return Exit{}, fmt.Errorf("%w: the exit carries %v units",
			ErrInvalidExitQuantity, definition.Quantity)
	}

	unit, err := theUnitOfTheBook(definition.Unit, ErrInvalidExitUnit)
	if err != nil {
		return Exit{}, err
	}

	if definition.Day.Time().IsZero() {
		return Exit{}, fmt.Errorf("%w: the exit carries the day it happened",
			ErrMissingExitDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Exit{}, fmt.Errorf("%w: the exit carries the word of the owner",
			ErrMissingExitConfirmation)
	}

	units := theUnitsOfTheProduct(held, recipeID)
	if len(units) < int(definition.Quantity) {
		return Exit{}, fmt.Errorf("%w: the book holds %d units of the product and the owner took %v",
			ErrNotEnoughUnitsToExit, len(units), definition.Quantity)
	}

	taken := units[:int(definition.Quantity)]

	exited := make([]ExitedUnit, 0, len(taken))
	cost := ledger.Amount(0)

	for _, one := range taken {
		price, err := theMoneyOfTheUnit(productions, one)
		if err != nil {
			return Exit{}, err
		}

		exited = append(exited, ExitedUnit{
			UnitID:       one.ID,
			ProductionID: one.ProductionID,
			Position:     one.Position,
			Grams:        one.Grams,
			ExpiresOn:    one.ExpiresOn,
		})

		cost += price
	}

	name := theNameOfTheProduct(productions, recipeID)

	return NewExit(own, ExitFact{
		RecipeID:      recipeID,
		RecipeName:    name,
		Kind:          definition.Kind,
		Day:           definition.Day,
		Quantity:      definition.Quantity,
		Unit:          unit,
		Cost:          cost,
		TaxTreatment:  TaxPendingTheProfessional,
		TaxQuestion:   theQuestionOfTheTaxes(definition.Kind),
		Units:         exited,
		Utterance:     definition.Utterance,
		ConfirmedWith: word,
	})
}

// NewExit builds the exit of the business out of what the book keeps.
//
// The error is ErrMissingBusiness when the exit is of no business,
// ErrMissingRecipe when it names no product, ErrUnknownExitKind when its
// kind is not one of the two of the book, ErrMissingExitDay when it carries
// no day, ErrInvalidExitQuantity when the quantity is not a whole number of
// units, ErrInvalidExitUnit when the unit is not the unit of a piece,
// ErrInvalidExitCost when the cost is negative, ErrMissingTaxTreatment
// when the exit carries no tax treatment, ErrNotEnoughUnitsToExit when the
// exit carries no unit, and ErrMissingExitConfirmation when it carries no
// word of the owner.
func NewExit(own business.ID, fact ExitFact) (Exit, error) {
	exit := Exit{
		BusinessID:    own,
		Kind:          fact.Kind,
		RecipeID:      fact.RecipeID,
		RecipeName:    strings.TrimSpace(fact.RecipeName),
		Day:           fact.Day,
		Quantity:      fact.Quantity,
		Unit:          strings.TrimSpace(fact.Unit),
		Cost:          fact.Cost,
		TaxTreatment:  fact.TaxTreatment,
		TaxQuestion:   strings.TrimSpace(fact.TaxQuestion),
		Units:         fact.Units,
		Utterance:     strings.TrimSpace(fact.Utterance),
		ConfirmedWith: strings.TrimSpace(fact.ConfirmedWith),
	}

	return exit.Checked()
}

// Checked answers the exit when it is whole, and the error when it is not.
//
// The rule of the domain: the exit belongs to a business, names the
// product it took, carries one of the two kinds of the book, a whole number
// of units with the unit of a piece, the day it happened, the word of the
// owner, the cost it released, the tax treatment it waits for and the units
// that left the book.
//
// A row that another writer broke is refused, and it is never read as an
// exit.
func (e Exit) Checked() (Exit, error) {
	if e.BusinessID <= 0 {
		return Exit{}, fmt.Errorf("%w: the exit is of the business %d",
			ErrMissingBusiness, e.BusinessID)
	}

	if !e.Kind.Valid() {
		return Exit{}, fmt.Errorf("%w: the kind of the exit is %q",
			ErrUnknownExitKind, e.Kind)
	}

	if e.RecipeID <= 0 || strings.TrimSpace(e.RecipeName) == "" {
		return Exit{}, fmt.Errorf("%w: the exit names the product it took",
			ErrMissingRecipe)
	}

	if e.Day.Time().IsZero() {
		return Exit{}, fmt.Errorf("%w: the exit carries the day it happened",
			ErrMissingExitDay)
	}

	if e.Quantity <= 0 || e.Quantity != math.Trunc(e.Quantity) {
		return Exit{}, fmt.Errorf("%w: the exit carries %v units",
			ErrInvalidExitQuantity, e.Quantity)
	}

	if e.Unit != ingredient.UnitPiece.String() {
		return Exit{}, fmt.Errorf("%w: the unit of the exit is %q",
			ErrInvalidExitUnit, e.Unit)
	}

	if e.Cost < 0 {
		return Exit{}, fmt.Errorf("%w: the cost of the exit is %d",
			ErrInvalidExitCost, e.Cost)
	}

	if !e.TaxTreatment.Valid() {
		return Exit{}, fmt.Errorf("%w: the tax treatment of the exit is %q",
			ErrMissingTaxTreatment, e.TaxTreatment)
	}

	if strings.TrimSpace(e.TaxQuestion) == "" {
		return Exit{}, fmt.Errorf("%w: the exit names no question about the taxes",
			ErrMissingTaxTreatment)
	}

	if len(e.Units) == 0 {
		return Exit{}, fmt.Errorf("%w: the exit carries no unit",
			ErrNotEnoughUnitsToExit)
	}

	if strings.TrimSpace(e.ConfirmedWith) == "" {
		return Exit{}, fmt.Errorf("%w: the exit carries the word of the owner",
			ErrMissingExitConfirmation)
	}

	return e, nil
}

// TheExpenseRole answers the role of the account the cost of the exit
// lands in.
//
// The rule of the domain: the consumption of the owner releases the cost
// like a sale does, and the cost of the sales is where it lands. The
// donation is a social expense of the business, and the account of the
// donation is where it lands.
//
// The error is ErrUnknownExitKind when the kind of the exit is not one of
// the two of the book.
func (e Exit) TheExpenseRole() account.Role {
	if e.Kind == ExitDonation {
		return account.RoleDonation
	}

	return account.RoleCostOfSales
}

// CostMovement answers the movement of the cost of the exit.
//
// The cost of the units that left the book leaves the inventory and lands
// in the account of the expense of the exit: the money of the stock is not
// lost from the book, it is the cost the business carries.
//
// The exit moves no money IN: nobody paid for the bread the owner consumed
// or for the bread the bakery gave away, and the only movement of the exit
// is this one: the cost of the units that left the book leaves the
// inventory.
//
// The description of the movement is the sentence of the owner when she
// said one, and the words of the book when she said none.
func (e Exit) CostMovement(expense, inventory account.ID) (ledger.Entry, error) {
	return ledger.NewEntry(e.BusinessID, expense, inventory, e.Cost, e.Day, e.Description())
}

// Description answers what the person reads in the book.
//
// The rule of the domain: the sentence of the owner is what she reads, and
// the words of the book are what she reads when she said no sentence: the
// kind of the exit, the product and the number of units.
func (e Exit) Description() string {
	if utterance := strings.TrimSpace(e.Utterance); utterance != "" {
		return utterance
	}

	return fmt.Sprintf("%s: %v unidades de %s", e.nameOfTheExit(), e.Quantity, e.RecipeName)
}

// nameOfTheExit answers the name the book gives to the kind of the exit.
//
// The rule of the domain: the owner reads the name of the exit in the book
// she keeps, and the name is the one of the two kinds of the book.
func (e Exit) nameOfTheExit() string {
	if e.Kind == ExitDonation {
		return "Donación"
	}

	return "Consumo"
}
