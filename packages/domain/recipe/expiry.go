// The expiry of what the bakery makes.
//
// The shelf life of a recipe is a declared constant, and it is approximate:
// the owner does not know it yet, and she corrects it when she knows it
// better. The correction is a fact of the business, and it is kept: the
// book remembers every correction she declared, and the last one is the
// shelf life that counts.
//
// Every unit of a production carries the day it expires, and the day is
// the day of the production plus the shelf life of the recipe. The unit
// keeps the days of its shelf life and expires on the first day it is no
// longer good.
//
// A unit that expired is never sold: the expiry is a rule of the book, and
// the sale that comes later reads it here.

// CorrectionID is the identity of a correction of the shelf life.
//
// The number is generated by the database. The type exists so that an
// identifier never travels as a plain integer by accident.
type CorrectionID int64

// ShelfLifeCorrection is the correction the owner declared of the shelf life
// of a recipe.
//
// The correction is kept: every one of them is a row of its own, and the
// last one the owner declared is the shelf life that counts. The correction
// carries the word of the owner, the way the recipe and the production do.
type ShelfLifeCorrection struct {
	// ID is the identity of the correction. It is empty until the storage
	// writes the row.
	ID CorrectionID

	// BusinessID is the business that owns the recipe.
	BusinessID business.ID

	// RecipeID is the recipe the correction is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the recipe. It is the name
	// of the recipe, and the recipe is the owner of it.
	RecipeName string

	// ShelfLifeDays is the number of days what the recipe makes keeps,
	// the way the owner corrected it.
	ShelfLifeDays int

	// Day is the day the correction was declared.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the correction.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// ShelfLifeDefinition is what the owner said about the shelf life.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type ShelfLifeDefinition struct {
	// RecipeID is the recipe the correction is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the recipe.
	RecipeName string

	// ShelfLifeDays is the number of days what the recipe makes keeps.
	ShelfLifeDays int

	// Day is the day the correction was declared.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word she used to confirm the correction.
	ConfirmedWith string
}

// CorrectShelfLife builds the correction of the shelf life of a recipe.
//
// The rules of the domain:
//
//   - the correction belongs to the business that owns the recipe: a
//     correction of the shelf life of another business is refused;
//   - the correction names the recipe it corrects;
//   - the number of days is positive: the shelf life of what a recipe
//     makes is a number of days, and zero days is no shelf life at all;
//   - the correction carries the day it was declared and the word of the
//     owner: the correction is written with her confirmation, the way the
//     recipe and the production are written.
func CorrectShelfLife(own business.ID, baked Recipe, definition ShelfLifeDefinition) (ShelfLifeCorrection, error) {
	if own <= 0 {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction is of the business %d",
			ErrMissingBusiness, own)
	}

	if baked.BusinessID != own {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the recipe %d belongs to the business %d",
			ErrWrongBusiness, baked.ID, baked.BusinessID)
	}

	if baked.ID <= 0 {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction names no recipe",
			ErrMissingRecipe)
	}

	if definition.ShelfLifeDays <= 0 {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction declares %d days of shelf life",
			ErrMissingShelfLife, definition.ShelfLifeDays)
	}

	if definition.Day.Time().IsZero() {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction carries the day it was declared",
			ErrMissingDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction carries the word of the owner",
			ErrMissingConfirmation)
	}

	return ShelfLifeCorrection{
		BusinessID:    own,
		RecipeID:      baked.ID,
		RecipeName:    strings.TrimSpace(baked.Name),
		ShelfLifeDays: definition.ShelfLifeDays,
		Day:           definition.Day,
		Utterance:     strings.TrimSpace(definition.Utterance),
		ConfirmedWith: word,
	}.Checked()
}

// Checked answers the correction when it is whole, and the error when it is
// not.
//
// The rule of the domain: the correction belongs to a business, names the
// recipe it corrects, carries a positive number of days, the day it was
// declared and the word of the owner.
//
// A row that another writer broke is refused, and it is never read as a
// correction.
func (c ShelfLifeCorrection) Checked() (ShelfLifeCorrection, error) {
	if c.BusinessID <= 0 {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction is of the business %d",
			ErrMissingBusiness, c.BusinessID)
	}

	if c.RecipeID <= 0 || strings.TrimSpace(c.RecipeName) == "" {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction names no recipe",
			ErrMissingRecipe)
	}

	if c.ShelfLifeDays <= 0 {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction declares %d days of shelf life",
			ErrMissingShelfLife, c.ShelfLifeDays)
	}

	if c.Day.Time().IsZero() {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction carries the day it was declared",
			ErrMissingDay)
	}

	if strings.TrimSpace(c.ConfirmedWith) == "" {
		return ShelfLifeCorrection{}, fmt.Errorf("%w: the correction carries the word of the owner",
			ErrMissingConfirmation)
	}

	return c, nil
}

// ShelfLifeOf answers the number of days what the recipe makes keeps.
//
// The rule of the domain: the shelf life the owner corrected is the one that
// counts, and the last correction she declared is the one that counts. The
// shelf life the recipe declares counts when she corrected nothing.
//
// The corrections of the other recipes are not hers: the shelf life of a
// recipe is corrected by the correction of that recipe alone.
func ShelfLifeOf(baked Recipe, corrections []ShelfLifeCorrection) int {
	last, found := lastCorrectionOf(baked.ID, corrections)
	if !found {
		return baked.ShelfLifeDays
	}

	return last.ShelfLifeDays
}

// lastCorrectionOf answers the correction the owner declared last of that
// recipe.
//
// The rule of the domain: the last correction is the one of the last day,
// and the one of the last identity when two of them share the day: the
// order of the book is never the order of the storage.
func lastCorrectionOf(of ID, corrections []ShelfLifeCorrection) (ShelfLifeCorrection, bool) {
	mine := make([]ShelfLifeCorrection, 0, len(corrections))

	for _, one := range corrections {
		if one.RecipeID == of {
			mine = append(mine, one)
		}
	}

	if len(mine) == 0 {
		return ShelfLifeCorrection{}, false
	}

	sort.SliceStable(mine, func(one, other int) bool {
		if mine[one].Day.Time().Equal(mine[other].Day.Time()) {
			return mine[one].ID < mine[other].ID
		}

		return mine[one].Day.Before(mine[other].Day)
	})

	return mine[len(mine)-1], true
}

// ExpiringUnit is a unit of the book of the business, read for the day it
// expires.
//
// It is the unit of the production, read with the production it came out of
// and the recipe it was made of: the row of the unit is one row, and the
// answer of the expiry is its projection.
type ExpiringUnit struct {
	// ProductionUnit is the unit that came out of the production: it
	// carries its identity, its position, its grams and the day it
	// expires.
	ProductionUnit

	// RecipeID is the recipe the unit was made of.
	RecipeID ID

	// RecipeName is the name the owner reads of the recipe.
	RecipeName string

	// ProducedOn is the day the production was made.
	ProducedOn ledger.Date
}

// Expiry is the answer of the read of what expires.
//
// It carries the day the answer was read on, because the days that are left
// of a unit are counted from that day, and the units of the book in the
// order they expire.
type Expiry struct {
	// Day is the day the answer was read on.
	Day ledger.Date

	// Units are the units of the book, in the order they expire.
	Units []ExpiringUnit
}

// ExpiringUnits answers the units of the book in the order they expire.
//
// The rule of the domain: the answer of the expiry is ordered by the day the
// units expire, and the unit that expires first is the first one: the
// expiry is what the owner asks about. The rotation - the unit that leaves a
// production - is another rule, and it does not live here.
//
// The units of the productions of another business are not in the answer:
// the expiry is read for one business, and the book never mixes them.
func ExpiringUnits(units []ExpiringUnit) []ExpiringUnit {
	ordered := make([]ExpiringUnit, len(units))
	copy(ordered, units)

	sort.SliceStable(ordered, func(one, other int) bool {
		if ordered[one].ExpiresOn.Time().Equal(ordered[other].ExpiresOn.Time()) {
			return ordered[one].ID < ordered[other].ID
		}

		return ordered[one].ExpiresOn.Before(ordered[other].ExpiresOn)
	})

	return ordered
}

// CorrectedUnit is a unit of the book whose day of expiry the owner
// corrected.
//
// It carries the day the unit expired on before the correction, because the
// storage writes the new day only when the unit still carries the old one:
// a unit that changed under the correction is refused.
type CorrectedUnit struct {
	// UnitID is the identity of the unit.
	UnitID UnitID

	// Was is the day the unit expired on before the correction.
	Was ledger.Date

	// Now is the day the unit expires on, the one the correction gives it.
	Now ledger.Date
}

// CorrectedUnits answers the units of the recipe whose expiry the
// correction moves.
//
// The rule of the domain:
//
//   - the correction touches the units of the recipe it corrects, and of no
//     other recipe: the shelf life of a bread does not move the expiry of
//     the cake;
//   - the new day of a unit is the day of its production plus the days the
//     owner corrected: the unit keeps the days of the shelf life it now
//     has, and it expires on the first day it is no longer good.
//
// The error is ErrMissingShelfLife when the number of days is not positive,
// and ErrMissingProductionDay when a unit carries no day of production: a
// unit the book cannot place in the time has no expiry to correct.
func CorrectedUnits(units []ExpiringUnit, of ID, days int) ([]CorrectedUnit, error) {
	if days <= 0 {
		return nil, fmt.Errorf("%w: the correction declares %d days of shelf life",
			ErrMissingShelfLife, days)
	}

	corrected := make([]CorrectedUnit, 0, len(units))

	for _, one := range units {
		if one.RecipeID != of {
			continue
		}

		if one.ProducedOn.Time().IsZero() {
			return nil, fmt.Errorf("%w: the unit %d carries no day of production",
				ErrMissingProductionDay, one.ID)
		}

		corrected = append(corrected, CorrectedUnit{
			UnitID: one.ID,
			Was:    one.ExpiresOn,
			Now:    ledger.NewDate(one.ProducedOn.Time().AddDate(0, 0, days)),
		})
	}

	return corrected, nil
}

// Checked answers the unit when it is whole, and the error when it is not.
//
// The rule of the domain: the unit carries the day it expires and the day it
// was made, and it expires on a day that is not before the day it was made.
//
// A row that another writer broke is refused, and it is never read as a
// unit of the book.
func (u ExpiringUnit) Checked() (ExpiringUnit, error) {
	if u.ExpiresOn.Time().IsZero() {
		return ExpiringUnit{}, fmt.Errorf("%w: the unit %d carries no day of expiry",
			ErrMissingExpiry, u.ID)
	}

	if u.ProducedOn.Time().IsZero() {
		return ExpiringUnit{}, fmt.Errorf("%w: the unit %d carries no day of production",
			ErrMissingProductionDay, u.ID)
	}

	if u.ExpiresOn.Before(u.ProducedOn) {
		return ExpiringUnit{}, fmt.Errorf("%w: the unit %d expires on %q, before the production of %q",
			ErrMissingProductionUnits, u.ID, u.ExpiresOn.String(), u.ProducedOn.String())
	}

	return u, nil
}

// Expired reports whether the unit expired on that day.
//
// The rule of the domain: the unit keeps the days of its shelf life and
// expires on the first day it is no longer good. A unit that expired is
// never sold.
func (u ProductionUnit) Expired(day ledger.Date) bool {
	if u.ExpiresOn.Time().IsZero() {
		return false
	}

	return !day.Before(u.ExpiresOn)
}

// DaysLeft answers how many days the unit keeps from that day.
//
// The rule of the domain: the days that are left are the days between the
// day and the day the unit expires. Zero days left is the day the unit
// expires, and the unit is already expired on it. A unit that expired
// already has no days left.
func (u ProductionUnit) DaysLeft(day ledger.Date) int {
	if u.ExpiresOn.Time().IsZero() {
		return 0
	}

	left := int(u.ExpiresOn.Time().Sub(day.Time()).Hours() / 24)
	if left < 0 {
		return 0
	}

	return left
}

// CheckSellable refuses the unit that expired.
//
// The rule of the domain: a unit that expired is never sold. The refusal
// names the day the unit expired, so the agent can tell the owner what it
// is talking about.
//
// The error is ErrExpiredUnit when the unit expired, and
// ErrMissingSaleDay when the day of the sale is not there: a sale of
// no day is a sale of nothing.
func (u ProductionUnit) CheckSellable(day ledger.Date) error {
	if day.Time().IsZero() {
		return fmt.Errorf("%w: the sale carries no day", ErrMissingSaleDay)
	}

	if u.Expired(day) {
		return fmt.Errorf("%w: the unit %d expired on %q",
			ErrExpiredUnit, u.ID, u.ExpiresOn.String())
	}

	return nil
}
