// The production of the bakery: what came out of the oven on one day.
//
// The production lives here, next to the recipe, because it is the recipe
// that is made: the recipe declares the yield of the units and the shelf
// life of them, and the production is the day those units came out.
//
// The package already imports the package of the purchase, where the layers
// of the stock live, and the direction of the dependencies forbids the
// package of the purchase from reaching for the recipe.

// ProductionID is the identity of a production.
//
// The number is generated by the database: it is the counter of the
// productions and not a number of the person. The type exists so that an
// identifier never travels as a plain integer by accident.
type ProductionID int64

// UnitID is the identity of a unit that came out of a production.
//
// The number is generated by the database. The type exists so that an
// identifier never travels as a plain integer by accident.
type UnitID int64

// Production is what the bakery made on a day.
//
// It carries the recipe it was made of, the day it was made, the grams that
// went in and the units that came out.
//
// The units are the yield of the recipe: the yield is a declared constant
// and the actual production is not measured per bake. Every unit carries the
// day it expires: the day of the production plus the shelf life of the
// recipe, which is approximate until the owner corrects it.
//
// The takes are the layers of the stock the production consumed, in the
// order they leave the stock: the oldest layer leaves first. The money of
// the production is the money of those layers, pro rata the quantity that
// was taken.
type Production struct {
	// ID is the identity of the production. It is empty until the storage
	// writes the row.
	ID ProductionID

	// BusinessID is the business that made the production.
	BusinessID business.ID

	// RecipeID is the recipe the production was made of.
	RecipeID ID

	// RecipeName is the name the owner reads of the recipe. It is the name
	// of the recipe, and the recipe is the owner of it.
	RecipeName string

	// Day is the day the production was made.
	Day ledger.Date

	// GramsIn is the grams that went into the production: the grams the
	// layers of the stock gave to it.
	GramsIn float64

	// Money is the money of what the layers gave, in whole pesos.
	Money ledger.Amount

	// Takes are the layers the production consumed, in the order they leave
	// the stock: the oldest one leaves first.
	Takes []purchase.Take

	// Remaining is what is left of the layers the production consumed: the
	// quantity each of them held and the quantity that is left of it.
	Remaining []purchase.Remaining

	// Units are the units that came out of the production, in the order
	// they were made.
	Units []ProductionUnit

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the production.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// ProductionUnit is one unit that came out of the production.
//
// The unit carries the weight of it and the day it expires: the day of the
// production plus the shelf life of the recipe.
type ProductionUnit struct {
	// ID is the identity of the unit. It is empty until the storage writes
	// the row.
	ID UnitID

	// ProductionID is the production the unit came out of.
	ProductionID ProductionID

	// Position is the order the unit was made in.
	Position int

	// Grams is the weight of the unit.
	Grams float64

	// ExpiresOn is the day the unit expires.
	ExpiresOn ledger.Date
}

// ProductionDefinition is what the owner said about the production.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type ProductionDefinition struct {
	// Day is the day the production was made.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word she used to confirm the production.
	ConfirmedWith string
}

// ProductionFact is what the book keeps of a production.
//
// The fact carries what the owner said and what the book derived: the
// recipe it was made of, the grams that went in and the units that came
// out.
type ProductionFact struct {
	// RecipeID is the recipe the production was made of.
	RecipeID ID

	// RecipeName is the name the owner reads of the recipe.
	RecipeName string

	// Day is the day the production was made.
	Day ledger.Date

	// GramsIn is the grams that went into the production.
	GramsIn float64

	// Money is the money of what the layers gave, in whole pesos.
	Money ledger.Amount

	// Takes are the layers the production consumed.
	Takes []purchase.Take

	// Remaining is what is left of the layers the production consumed.
	Remaining []purchase.Remaining

	// Units are the units that came out of the production.
	Units []ProductionUnit

	// Utterance is the sentence of the owner, verbatim.
	Utterance string

	// ConfirmedWith is the word she used to confirm the production.
	ConfirmedWith string
}

// ProductionOf derives the production of the recipe on the day.
//
// The rules of the domain:
//
//   - the production belongs to a business, names the recipe it was made of
//     and carries the day it was made;
//   - the production carries the word of the owner: it is written with her
//     confirmation, the way the recipe is written;
//   - the recipe consumes the layers of the stock in the order of the FIFO:
//     the oldest layer leaves first;
//   - the grams that went in are the grams the layers gave, and the money
//     of the production is the money of the layers, pro rata the quantity
//     that was taken;
//   - the units that came out are the yield of the recipe, and every one of
//     them carries the day it expires: the day of the production plus the
//     shelf life of the recipe;
//   - a production the stock cannot cover is refused, and so is a
//     production whose ingredients the book cannot weigh.
func ProductionOf(
	baked Recipe,
	layers []purchase.Layer,
	catalog ingredient.Catalog,
	definition ProductionDefinition,
) (Production, error) {
	if baked.BusinessID <= 0 {
		return Production{}, fmt.Errorf("%w: the production is of the business %d",
			ErrMissingBusiness, baked.BusinessID)
	}

	if definition.Day.Time().IsZero() {
		return Production{}, fmt.Errorf("%w: the production carries the day it was made",
			ErrMissingProductionDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Production{}, fmt.Errorf("%w: the production carries the word of the owner",
			ErrMissingProductionConfirmation)
	}

	if baked.Yield.Units <= 0 || baked.Yield.Grams <= 0 {
		return Production{}, fmt.Errorf("%w: the recipe declares %d units of %v grams",
			ErrInvalidYield, baked.Yield.Units, baked.Yield.Grams)
	}

	takes := make([]purchase.Take, 0)
	remaining := make([]purchase.Remaining, 0)
	grams := 0.0
	money := ledger.Amount(0)

	for _, one := range gramsOfTheRecipe(baked) {
		item, held := catalog.Find(one.IngredientID)
		if !held {
			return Production{}, fmt.Errorf("%w: the ingredient %d of the recipe is not one of the catalog of the business",
				ErrUnknownIngredient, one.IngredientID)
		}

		consumption, err := purchase.Consume(layers, one.IngredientID, one.Grams, item)
		if err != nil {
			return Production{}, err
		}

		if consumption.Unknown {
			return Production{}, fmt.Errorf("%w: %s", ErrUnknownStock, consumption.Reason)
		}

		if consumption.Missing > 0 {
			return Production{}, fmt.Errorf("%w: the stock does not hold %v grams of %s",
				ErrMissingStock, consumption.Missing, item.Name)
		}

		takes = append(takes, consumption.Takes...)
		remaining = append(remaining, consumption.Remaining...)
		grams += consumption.Taken
		money += consumption.Money
	}

	return NewProduction(baked.BusinessID, ProductionFact{
		RecipeID:      baked.ID,
		RecipeName:    baked.Name,
		Day:           definition.Day,
		GramsIn:       grams,
		Money:         money,
		Takes:         takes,
		Remaining:     remaining,
		Units:         unitsOfTheProduction(baked, definition.Day),
		Utterance:     definition.Utterance,
		ConfirmedWith: word,
	})
}

// NewProduction builds the production of the business out of what the book
// keeps.
//
// The rule of the domain: the production belongs to a business, names the
// recipe it was made of, carries the day it was made, the grams that went
// in and the units that came out, and it carries the word of the owner.
//
// The error is ErrMissingBusiness when the production is of no business,
// ErrMissingRecipe when it names no recipe, ErrMissingProductionDay when it
// carries no day, ErrMissingProductionGrams when it carries no grams that
// went in, ErrMissingProductionUnits when it made no unit, and
// ErrMissingProductionConfirmation when it carries no word of the owner.
func NewProduction(own business.ID, fact ProductionFact) (Production, error) {
	production := Production{
		BusinessID:    own,
		RecipeID:      fact.RecipeID,
		RecipeName:    strings.TrimSpace(fact.RecipeName),
		Day:           fact.Day,
		GramsIn:       fact.GramsIn,
		Money:         fact.Money,
		Takes:         fact.Takes,
		Remaining:     fact.Remaining,
		Units:         fact.Units,
		Utterance:     strings.TrimSpace(fact.Utterance),
		ConfirmedWith: strings.TrimSpace(fact.ConfirmedWith),
	}

	return production.Checked()
}

// Checked answers the production when it is whole, and the error when it is
// not.
//
// The rule of the domain: the production belongs to a business, names the
// recipe it was made of, carries the day it was made, the grams that went
// in and the units that came out, and it carries the word of the owner.
//
// A row that another writer broke is refused, and it is never read as a
// production.
func (p Production) Checked() (Production, error) {
	if p.BusinessID <= 0 {
		return Production{}, fmt.Errorf("%w: the production is of the business %d",
			ErrMissingBusiness, p.BusinessID)
	}

	if p.RecipeID <= 0 || strings.TrimSpace(p.RecipeName) == "" {
		return Production{}, fmt.Errorf("%w: the production names no recipe",
			ErrMissingRecipe)
	}

	if p.Day.Time().IsZero() {
		return Production{}, fmt.Errorf("%w: the production carries the day it was made",
			ErrMissingProductionDay)
	}

	if p.GramsIn <= 0 {
		return Production{}, fmt.Errorf("%w: the production carries the grams that went in",
			ErrMissingProductionGrams)
	}

	if p.Money < 0 {
		return Production{}, fmt.Errorf("%w: the money of the production is %d",
			ErrInvalidProductionMoney, p.Money)
	}

	if len(p.Units) == 0 {
		return Production{}, fmt.Errorf("%w: the production made no unit",
			ErrMissingProductionUnits)
	}

	for index, one := range p.Units {
		if one.Position != index+1 {
			return Production{}, fmt.Errorf("%w: the unit %d is the unit %d of the production",
				ErrMissingProductionUnits, one.Position, index+1)
		}

		if one.Grams <= 0 {
			return Production{}, fmt.Errorf("%w: the unit %d weighs %v grams",
				ErrMissingProductionGrams, index+1, one.Grams)
		}

		if one.ExpiresOn.Time().IsZero() {
			return Production{}, fmt.Errorf("%w: the unit %d carries no day of expiry",
				ErrMissingProductionUnits, index+1)
		}

		if one.ExpiresOn.Before(p.Day) {
			return Production{}, fmt.Errorf("%w: the unit %d expires on %q, before the production of %q",
				ErrMissingProductionUnits, index+1, one.ExpiresOn.String(), p.Day.String())
		}
	}

	if strings.TrimSpace(p.ConfirmedWith) == "" {
		return Production{}, fmt.Errorf("%w: the production carries the word of the owner",
			ErrMissingProductionConfirmation)
	}

	return p, nil
}

// TheRecipeNamed answers the one recipe the owner named.
//
// The rule of the domain: the name of a recipe is not unique inside the
// business, and a production names ONE recipe: the book never guesses which
// recipe she made, and it never writes a production against two of them.
//
// The error is ErrUnknownRecipe when the business holds no recipe with that
// name, and ErrAmbiguousRecipe when it holds more than one.
func TheRecipeNamed(recipes []Recipe, name string) (Recipe, error) {
	found := Named(recipes, name)

	switch len(found) {
	case 0:
		return Recipe{}, fmt.Errorf("%w: the business holds no recipe named %q", ErrUnknownRecipe, name)
	case 1:
		return found[0], nil
	default:
		return Recipe{}, fmt.Errorf("%w: the business holds %d recipes named %q",
			ErrAmbiguousRecipe, len(found), name)
	}
}

// unitsOfTheProduction answers the units that came out of the production.
//
// The rule of the domain: the units are the yield of the recipe - the yield
// is a declared constant and the actual production is not measured per bake
// - and every one of them expires on the day of the production plus the
// shelf life of the recipe.
func unitsOfTheProduction(baked Recipe, day ledger.Date) []ProductionUnit {
	expires := ledger.NewDate(day.Time().AddDate(0, 0, baked.ShelfLifeDays))

	units := make([]ProductionUnit, 0, baked.Yield.Units)

	for position := 1; position <= baked.Yield.Units; position++ {
		units = append(units, ProductionUnit{
			Position:  position,
			Grams:     baked.Yield.Grams,
			ExpiresOn: expires,
		})
	}

	return units
}
