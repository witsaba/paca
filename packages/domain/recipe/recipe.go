// Package recipe holds the model of the recipe of the bakery: the guide to
// learn and to teach, and not a list of ingredients.
//
// A recipe carries the name the owner reads, the ingredients with their
// grams, the steps with their times, their temperatures and their cues, the
// yield of what it makes and the shelf life of it. The numbers of the
// process live here; the lessons live in the memory of Paca.
//
// The ingredient of a recipe is the ingredient of the catalog: the recipe
// carries the identity of the ingredient and the grams of it, and never a
// second copy of the flour. The package imports the package of the
// ingredient, and never the other way round.
//
// The yield is a declared constant: the number of units the recipe makes and
// the weight of each one. It is never measured per bake.
//
// The steps keep their order, and a step may be named by its cue: the sign
// the owner looks for. A step carries its time and its temperature when the
// owner named them, and neither when she did not.
//
// The domain refuses a recipe that is not whole: no name, no yield, an
// ingredient without its grams, a step without its instruction. The refusal
// says what the agent has to ask for.
//
// The cost of a batch of the recipe is here too: it is derived from the
// layers of the stock that the recipe consumes, and it is never typed.
//
// The labor of the bakery is here as well: the hours the owner works, in
// the three kinds of the labor - the hands, the oven and the waiting - the
// value of the hour she declares, and the labor of a batch, which is
// derived from the hours of the steps of the recipe. The labor is a layer
// of the cost of its own, and it is never hidden inside the direct cost.
//
// The package imports nothing but the standard library, the model of the
// business that owns the recipe, the model of the catalog of the ingredients
// it names and the model of the stock it is valued with.
package recipe

import (
	"fmt"
	"strings"
	"time"

	"github.com/witsaba/paca/packages/domain/business"
	"github.com/witsaba/paca/packages/domain/ingredient"
)

// ID is the identity of a recipe.
//
// The number is generated by the database: it is the counter of the recipes
// and not a number of the person. The type exists so that an identifier
// never travels as a plain integer by accident.
type ID int64

// AbsoluteZero is the lowest temperature a step may carry, in degrees
// Celsius.
//
// It is the rule of the physics and not a promise of the oven: a step below
// it is a number nobody can bake at.
const AbsoluteZero = -273.15

// Yield is the declared constant of what a recipe makes.
//
// It is the number of units the recipe makes and the weight of each one. It
// is declared by the owner and never measured per bake: the actual
// production is a fact of its own.
type Yield struct {
	// Units is the number of units the recipe makes.
	Units int

	// Grams is the weight of one unit, in grams.
	Grams float64
}

// NewYield builds the yield of a recipe.
//
// The rule of the domain: the yield is positive. A recipe that says how
// much it makes says a number of units and a weight, and both of them are
// there.
func NewYield(units int, grams float64) (Yield, error) {
	if units <= 0 {
		return Yield{}, fmt.Errorf("%w: the yield is %d units", ErrInvalidYield, units)
	}

	if grams <= 0 {
		return Yield{}, fmt.Errorf("%w: the weight of the unit is %v grams", ErrInvalidYield, grams)
	}

	return Yield{Units: units, Grams: grams}, nil
}

// Ingredient is an ingredient of a recipe.
//
// It carries the identity of the ingredient of the catalog and the grams of
// it, and nothing else: the recipe never carries a second copy of the
// flour.
type Ingredient struct {
	// IngredientID is the identity of the ingredient of the catalog.
	IngredientID ingredient.ID

	// Grams is how many grams of it the recipe needs.
	Grams float64
}

// NewIngredient builds an ingredient of a recipe.
//
// The rule of the domain: the grams are positive. The identity of the
// ingredient is not empty: a recipe that names nothing of the catalog has
// no ingredient of its own.
func NewIngredient(id ingredient.ID, grams float64) (Ingredient, error) {
	if id == 0 {
		return Ingredient{}, fmt.Errorf("%w: the ingredient of a recipe names nothing of the catalog",
			ErrUnknownIngredient)
	}

	if grams <= 0 {
		return Ingredient{}, fmt.Errorf("%w: the grams of the ingredient %d are %v", ErrMissingGrams, id, grams)
	}

	return Ingredient{IngredientID: id, Grams: grams}, nil
}

// Step is one step of the process of a recipe.
//
// A step carries its time and its temperature when the owner named them,
// and neither when she did not: the zero of the time and of the temperature
// is the absence of them, because a number PACA invented is a lie in the
// guide.
//
// The step carries the kind of the labor it is: the hands, the oven or the
// waiting. The labor of a batch is derived from the hours of its steps,
// and the kind is what says in which of the three kinds the hours of the
// step are counted. The kind the owner did not name is the labor of the
// hands.
type Step struct {
	// Instruction is what the owner does in this step.
	Instruction string

	// Cue is the sign the owner looks for: the dough that holds the
	// shape. It is empty when the owner named none.
	Cue string

	// Minutes is the time of the step, in minutes. It is zero when the
	// owner named none.
	Minutes int

	// Temperature is the temperature of the step, in degrees Celsius. It
	// is zero when the owner named none.
	Temperature float64

	// Kind is the kind of the labor the step is: the hands, the oven or
	// the waiting.
	Kind LaborKind
}

// NewStep builds a step of a recipe.
//
// The rule of the domain: the instruction is not empty, the temperature is
// not below the absolute zero, and the kind of the labor is one of the
// three kinds of the book.
//
// The kind the owner did not name is the labor of the hands: a step she did
// not qualify is a step she did with her hands.
func NewStep(instruction, cue string, minutes int, temperature float64, kind LaborKind) (Step, error) {
	trimmed := strings.TrimSpace(instruction)
	if trimmed == "" {
		return Step{}, fmt.Errorf("%w: the step carries no instruction", ErrMissingInstruction)
	}

	if temperature < AbsoluteZero {
		return Step{}, fmt.Errorf("%w: the temperature of the step is %v degrees", ErrInvalidTemperature, temperature)
	}

	labour, err := ParseLaborKind(string(kind))
	if err != nil {
		return Step{}, err
	}

	return Step{
		Instruction: trimmed,
		Cue:         strings.TrimSpace(cue),
		Minutes:     minutes,
		Temperature: temperature,
		Kind:        labour,
	}, nil
}

// Definition is what the owner says about a recipe.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type Definition struct {
	// Name is the name the owner reads.
	Name string

	// Ingredients are the ingredients of the recipe, with their grams.
	Ingredients []Ingredient

	// Steps are the steps of the process, in the order the owner said
	// them.
	Steps []Step

	// Yield is what the recipe makes.
	Yield Yield

	// ShelfLifeDays is the number of days what the recipe makes keeps.
	ShelfLifeDays int

	// Utterance is the sentence of the owner, verbatim. It is optional:
	// the recipe is the record, and the sentence is kept with it when she
	// said one.
	Utterance string

	// ConfirmedWith is the word she used to confirm the recipe.
	ConfirmedWith string
}

// Recipe is the guide of the bakery: what it makes, and how.
//
// A recipe never changes on its own: it is written with the word of the
// owner, and the owner corrects it later.
type Recipe struct {
	// ID is the identity of the recipe. It is empty until the storage
	// writes the row.
	ID ID

	// BusinessID is the business that owns the recipe.
	BusinessID business.ID

	// Name is the name the owner reads.
	Name string

	// Ingredients are the ingredients of the recipe, with their grams.
	Ingredients []Ingredient

	// Steps are the steps of the process, in the order the owner said
	// them.
	Steps []Step

	// Yield is what the recipe makes.
	Yield Yield

	// ShelfLifeDays is the number of days what the recipe makes keeps.
	ShelfLifeDays int

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the recipe.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// WithShelfLife answers the recipe with the shelf life that counts.
//
// The rule of the domain: the shelf life the owner corrected is the one that
// counts, and the last correction she declared is the one that counts. The
// use case reads the corrections and asks the domain which shelf life
// applies; the recipe itself never decides it.
func (r Recipe) WithShelfLife(days int) Recipe {
	r.ShelfLifeDays = days

	return r
}

// New builds the recipe of a business.
//
// The rules of the domain hold here:
//
//   - the name is not empty: a recipe without a name has nothing to show in
//     the book of the business;
//   - the word of the confirmation is not empty: it is kept with the record;
//   - the recipe carries at least one ingredient, and every one of them
//     carries its grams;
//   - the recipe carries at least one step, and every one of them carries
//     its instruction;
//   - the yield is positive: it is the declared constant of what the recipe
//     makes;
//   - the shelf life is positive: what the recipe makes keeps a number of
//     days, and the owner corrects it later.
func New(own business.ID, definition Definition) (Recipe, error) {
	name := strings.TrimSpace(definition.Name)
	if name == "" {
		return Recipe{}, fmt.Errorf("%w: the recipe carries no name", ErrMissingName)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Recipe{}, fmt.Errorf("%w: the recipe carries no word of the owner", ErrMissingConfirmation)
	}

	if len(definition.Ingredients) == 0 {
		return Recipe{}, fmt.Errorf("%w: the recipe names nothing of the catalog", ErrNoIngredients)
	}

	ingredients := make([]Ingredient, 0, len(definition.Ingredients))
	for _, one := range definition.Ingredients {
		if one.Grams <= 0 {
			return Recipe{}, fmt.Errorf("%w: the grams of the ingredient %d are %v",
				ErrMissingGrams, one.IngredientID, one.Grams)
		}

		if one.IngredientID == 0 {
			return Recipe{}, fmt.Errorf("%w: the recipe names nothing of the catalog", ErrUnknownIngredient)
		}

		ingredients = append(ingredients, one)
	}

	if len(definition.Steps) == 0 {
		return Recipe{}, fmt.Errorf("%w: the recipe teaches nothing", ErrNoSteps)
	}

	steps := make([]Step, 0, len(definition.Steps))
	for _, one := range definition.Steps {
		if strings.TrimSpace(one.Instruction) == "" {
			return Recipe{}, fmt.Errorf("%w: a step of the recipe carries no instruction", ErrMissingInstruction)
		}

		labour, err := ParseLaborKind(string(one.Kind))
		if err != nil {
			return Recipe{}, err
		}

		one.Kind = labour

		steps = append(steps, one)
	}

	if definition.Yield.Units <= 0 || definition.Yield.Grams <= 0 {
		return Recipe{}, fmt.Errorf("%w: the recipe declares %d units of %v grams",
			ErrInvalidYield, definition.Yield.Units, definition.Yield.Grams)
	}

	if definition.ShelfLifeDays <= 0 {
		return Recipe{}, fmt.Errorf("%w: the recipe declares %d days of shelf life",
			ErrMissingShelfLife, definition.ShelfLifeDays)
	}

	return Recipe{
		BusinessID:    own,
		Name:          name,
		Ingredients:   ingredients,
		Steps:         steps,
		Yield:         definition.Yield,
		ShelfLifeDays: definition.ShelfLifeDays,
		Utterance:     strings.TrimSpace(definition.Utterance),
		ConfirmedWith: word,
	}, nil
}
