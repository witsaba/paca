// The sale of the bakery: what she sold, and what it cost her.
//
// The sale is a movement of the book, and it is recorded as one from the
// start: the money the client paid lands in the account that receives it,
// and the cost of the units that left the book leaves the inventory.
//
// The sale takes the units of the product that expire first - the rotation
// of the perishable output - and it refuses the sale of a unit that
// expired: the sale is refused, and the owner is told to record the waste
// of it. The sale writes no waste of its own: the waste is a record of its
// own, with its reason.
//
// The cost of the units sold is derived, never typed: it is the money of
// the production the unit came out of, divided by the units that
// production made. The FIFO of the valuation is another rule: the FIFO of
// the layers was already taken when the production consumed them, so the
// money of the production is already FIFO-valued, and the sale reads that
// money. It never recomputes a valuation of its own.
//
// The price of the sale is what the client paid, and the owner says it: the
// price list of the products is a later work, and the book never infers
// the money of a sale.

// SaleID is the identity of a sale.
//
// The number is generated by the database. The type exists so that an
// identifier never travels as a plain integer by accident.
type SaleID int64

// SoldUnit is a unit of a production that the sale took out of the book.
//
// The unit carries the production it came out of: the cost of the sale is
// the money of that production, and the analysis of the sale reads it from
// here.
type SoldUnit struct {
	// UnitID is the identity of the unit that left the book.
	UnitID UnitID

	// ProductionID is the production the unit came out of.
	ProductionID ProductionID

	// Position is the order the unit was made in.
	Position int

	// Grams is the weight of the unit.
	Grams float64

	// ExpiresOn is the day the unit expires on.
	ExpiresOn ledger.Date
}

// Sale is what the bakery sold.
//
// It carries the product, the quantity, the unit, the money the client
// paid and the cost the sale released. The units that left the book travel
// with it: they are the units that expired first, and they are the ones a
// later analysis reads.
type Sale struct {
	// ID is the identity of the sale. It is empty until the storage
	// writes the row.
	ID SaleID

	// BusinessID is the business that owns the sale.
	BusinessID business.ID

	// RecipeID is the product the sale is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product. It is the
	// name of the recipe, and the recipe is the owner of it.
	RecipeName string

	// Day is the day the sale happened.
	Day ledger.Date

	// Quantity is how many units of the product the bakery sold.
	Quantity float64

	// Unit is the unit of that quantity: the sale of the bakery counts
	// the units it sold.
	Unit string

	// Money is the money the client paid, in whole pesos.
	Money ledger.Amount

	// Cost is the cost of the units that left the book, in whole pesos:
	// the cost the sale releases.
	Cost ledger.Amount

	// Units are the units of the production that left the book, in the
	// order they expire: the one that expires first is the first one.
	Units []SoldUnit

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the sale.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// SaleDefinition is what the owner said about the sale.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type SaleDefinition struct {
	// RecipeID is the product the sale is of. It is zero when the owner
	// names the product with its name.
	RecipeID ID

	// RecipeName is the name the owner reads of the product she sold. It
	// is empty when she names the product with its identity.
	RecipeName string

	// Quantity is how many units of the product the bakery sold.
	Quantity float64

	// Unit is the unit of that quantity. It is empty when the owner named
	// none, and the sale counts the units it sold then.
	Unit string

	// Money is the money the client paid, in whole pesos.
	Money ledger.Amount

	// Day is the day the sale happened.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word she used to confirm the sale.
	ConfirmedWith string
}

// SaleFact is what the book keeps of a sale.
//
// The fact carries what the owner said and what the book derived: the units
// that left the book and the cost they were worth.
type SaleFact struct {
	// RecipeID is the product the sale is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product.
	RecipeName string

	// Day is the day the sale happened.
	Day ledger.Date

	// Quantity is how many units of the product the bakery sold.
	Quantity float64

	// Unit is the unit of that quantity.
	Unit string

	// Money is the money the client paid, in whole pesos.
	Money ledger.Amount

	// Cost is the cost the sale released, in whole pesos.
	Cost ledger.Amount

	// Units are the units of the production that left the book.
	Units []SoldUnit

	// Utterance is the sentence of the owner, verbatim.
	Utterance string

	// ConfirmedWith is the word she used to confirm the sale.
	ConfirmedWith string
}

// SaleOf builds the sale the owner confirmed.
//
// The rules of the domain:
//
//   - the sale belongs to a business and names the product it sold: the
//     name of a product is not unique inside the business, and a name that
//     more than one product carries is refused, because the book never
//     guesses which product she sold;
//   - the quantity is positive and whole: the sale of the bakery counts
//     the units it sold, and the book never splits a unit;
//   - the unit is the unit of a piece: the book never converts a weight
//     into a number of units;
//   - the money is positive: a sale moves money in, and the money is what
//     the client paid, never an inference of the book;
//   - the sale carries the day it happened and the word of the owner: the
//     sale is written with her confirmation, the way the production and
//     the waste are written;
//   - the units that leave the book are the units of the product that are
//     still in it, in the order they expire: the one that expires first is
//     the first one;
//   - a unit that expired is never sold: the sale is refused, and the
//     owner is told to record the waste of it. The sale writes no waste of
//     its own: the waste is a record of its own, with its reason;
//   - the cost of the sale is the money of the units that left: the money
//     of the production they came out of, divided by the units that
//     production made. The money of the book counts whole pesos.
func SaleOf(
	own business.ID,
	productions []Production,
	held []ExpiringUnit,
	definition SaleDefinition,
) (Sale, error) {
	if own <= 0 {
		return Sale{}, fmt.Errorf("%w: the sale is of the business %d",
			ErrMissingBusiness, own)
	}

	recipeID, err := theProductOfTheBook(productions, definition.RecipeID, definition.RecipeName, "sale")
	if err != nil {
		return Sale{}, err
	}

	if definition.Quantity <= 0 {
		return Sale{}, fmt.Errorf("%w: the sale carries %v units",
			ErrInvalidSaleQuantity, definition.Quantity)
	}

	if definition.Quantity != math.Trunc(definition.Quantity) {
		return Sale{}, fmt.Errorf("%w: the sale carries %v units",
			ErrInvalidSaleQuantity, definition.Quantity)
	}

	unit, err := theUnitOfTheBook(definition.Unit, ErrInvalidSaleUnit)
	if err != nil {
		return Sale{}, err
	}

	if definition.Money <= 0 {
		return Sale{}, fmt.Errorf("%w: the sale carries %d pesos",
			ErrInvalidSaleMoney, definition.Money)
	}

	if definition.Day.Time().IsZero() {
		return Sale{}, fmt.Errorf("%w: the sale carries the day it was made",
			ErrMissingSaleDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Sale{}, fmt.Errorf("%w: the sale carries the word of the owner",
			ErrMissingSaleConfirmation)
	}

	units := theUnitsOfTheProduct(held, recipeID)
	if len(units) < int(definition.Quantity) {
		return Sale{}, fmt.Errorf("%w: the book holds %d units of the product and the owner sold %v",
			ErrNotEnoughUnitsToSell, len(units), definition.Quantity)
	}

	taken := units[:int(definition.Quantity)]

	sold := make([]SoldUnit, 0, len(taken))
	cost := ledger.Amount(0)

	for _, one := range taken {
		// The rule of the domain: a unit that expired is never sold. The
		// sale does not skip the expired unit to take a fresher one: the
		// sale is refused, and the owner is told to record the waste of
		// it. The sale writes no waste of its own.
		if err := one.CheckSellable(definition.Day); err != nil {
			return Sale{}, err
		}

		price, err := theMoneyOfTheUnit(productions, one)
		if err != nil {
			return Sale{}, err
		}

		sold = append(sold, SoldUnit{
			UnitID:       one.ID,
			ProductionID: one.ProductionID,
			Position:     one.Position,
			Grams:        one.Grams,
			ExpiresOn:    one.ExpiresOn,
		})

		cost += price
	}

	name := theNameOfTheProduct(productions, recipeID)

	return NewSale(own, SaleFact{
		RecipeID:      recipeID,
		RecipeName:    name,
		Day:           definition.Day,
		Quantity:      definition.Quantity,
		Unit:          unit,
		Money:         definition.Money,
		Cost:          cost,
		Units:         sold,
		Utterance:     definition.Utterance,
		ConfirmedWith: word,
	})
}

// NewSale builds the sale of the business out of what the book keeps.
//
// The error is ErrMissingBusiness when the sale is of no business,
// ErrMissingRecipe when it names no product, ErrMissingSaleDay when it
// carries no day, ErrInvalidSaleQuantity when the quantity is not a whole
// number of units, ErrInvalidSaleUnit when the unit is not the unit of a
// piece, ErrInvalidSaleMoney when the money is not positive,
// ErrInvalidSaleCost when the cost is negative, ErrNotEnoughUnitsToSell
// when the sale carries no unit, and ErrMissingSaleConfirmation when it
// carries no word of the owner.
func NewSale(own business.ID, fact SaleFact) (Sale, error) {
	sale := Sale{
		BusinessID:    own,
		RecipeID:      fact.RecipeID,
		RecipeName:    strings.TrimSpace(fact.RecipeName),
		Day:           fact.Day,
		Quantity:      fact.Quantity,
		Unit:          strings.TrimSpace(fact.Unit),
		Money:         fact.Money,
		Cost:          fact.Cost,
		Units:         fact.Units,
		Utterance:     strings.TrimSpace(fact.Utterance),
		ConfirmedWith: strings.TrimSpace(fact.ConfirmedWith),
	}

	return sale.Checked()
}

// Checked answers the sale when it is whole, and the error when it is not.
//
// The rule of the domain: the sale belongs to a business, names the
// product it sold, carries a whole number of units with the unit of a
// piece, carries the money the client paid, carries the cost it released,
// carries the day it happened and the word of the owner, and it carries the
// units that left the book.
//
// A row that another writer broke is refused, and it is never read as a
// sale.
func (s Sale) Checked() (Sale, error) {
	if s.BusinessID <= 0 {
		return Sale{}, fmt.Errorf("%w: the sale is of the business %d",
			ErrMissingBusiness, s.BusinessID)
	}

	if s.RecipeID <= 0 || strings.TrimSpace(s.RecipeName) == "" {
		return Sale{}, fmt.Errorf("%w: the sale names the product it sold",
			ErrMissingRecipe)
	}

	if s.Day.Time().IsZero() {
		return Sale{}, fmt.Errorf("%w: the sale carries the day it was made",
			ErrMissingSaleDay)
	}

	if s.Quantity <= 0 || s.Quantity != math.Trunc(s.Quantity) {
		return Sale{}, fmt.Errorf("%w: the sale carries %v units",
			ErrInvalidSaleQuantity, s.Quantity)
	}

	if s.Unit != ingredient.UnitPiece.String() {
		return Sale{}, fmt.Errorf("%w: the unit of the sale is %q",
			ErrInvalidSaleUnit, s.Unit)
	}

	if s.Money <= 0 {
		return Sale{}, fmt.Errorf("%w: the sale carries %d pesos",
			ErrInvalidSaleMoney, s.Money)
	}

	if s.Cost < 0 {
		return Sale{}, fmt.Errorf("%w: the cost of the sale is %d",
			ErrInvalidSaleCost, s.Cost)
	}

	if len(s.Units) == 0 {
		return Sale{}, fmt.Errorf("%w: the sale carries no unit",
			ErrNotEnoughUnitsToSell)
	}

	if strings.TrimSpace(s.ConfirmedWith) == "" {
		return Sale{}, fmt.Errorf("%w: the sale carries the word of the owner",
			ErrMissingSaleConfirmation)
	}

	return s, nil
}

// MoneyMovement answers the movement of the money of the sale.
//
// The money of the sale lands in the account that receives it - the cash of
// the business, or the account the owner named - and it comes from the
// account of the sales: the client paid, and the business earned.
//
// The description of the movement is the sentence of the owner when she
// said one, and the words of the book when she said none.
func (s Sale) MoneyMovement(receiving, sales account.ID) (ledger.Entry, error) {
	return ledger.NewEntry(s.BusinessID, receiving, sales, s.Money, s.Day, s.Description())
}

// CostMovement answers the movement of the cost of the sale.
//
// The cost of the units that left the book leaves the inventory and lands
// in the account of the cost of the sales: the money of the stock is not
// lost from the book, it is the cost the business carries.
//
// The description of the movement is the words of the book, with the
// sentence of the owner when she said one.
func (s Sale) CostMovement(costOfSales, inventory account.ID) (ledger.Entry, error) {
	return ledger.NewEntry(s.BusinessID, costOfSales, inventory, s.Cost, s.Day, s.CostDescription())
}

// Description answers what the person reads in the book.
//
// The rule of the domain: the sentence of the owner is what she reads, and
// the words of the book are what she reads when she said no sentence: the
// product and the number of units.
func (s Sale) Description() string {
	if utterance := strings.TrimSpace(s.Utterance); utterance != "" {
		return utterance
	}

	return fmt.Sprintf("Venta: %v unidades de %s", s.Quantity, s.RecipeName)
}

// CostDescription answers what the person reads in the book for the cost
// of the sale.
//
// The rule of the domain: the cost of the sale is its own movement, and it
// says what it cost.
func (s Sale) CostDescription() string {
	if utterance := strings.TrimSpace(s.Utterance); utterance != "" {
		return "Costo de la venta: " + utterance
	}

	return fmt.Sprintf("Costo de la venta: %v unidades de %s", s.Quantity, s.RecipeName)
}

// TheReceivingAccount answers the account the money of the sale lands in.
//
// The rule of the domain: the money lands in the cash of the business, and
// in the account the owner names when she names another one: the bakery
// sells for cash, and it sells for the bank when the client paid with the
// bank.
//
// The error is account.ErrNotFound when the account the owner names is not
// one of the book of the business, and when the book holds no cash.
func TheReceivingAccount(accounts []account.Account, named account.ID) (account.Account, error) {
	if named == 0 {
		found, err := account.OfRole(accounts, account.RoleCash)
		if err != nil {
			return account.Account{}, fmt.Errorf("%w: the business has no cash to sell with", err)
		}

		return found, nil
	}

	for _, one := range accounts {
		if one.ID == named {
			return one, nil
		}
	}

	return account.Account{}, fmt.Errorf("%w: the account %d is not one of the book of the business",
		account.ErrNotFound, named)
}
