// The waste of the bakery: what she lost, and what it was worth.
//
// The waste is a movement of the book, and it is recorded as one from the
// start: the product, the quantity, the unit and the reason are what the
// owner said, and the reason is what a later analysis reads.
//
// The waste releases the cost of what it was worth: the units that leave the
// book are the units of the product that expire first, and the money of the
// waste is the money of those units - the money of the production they came
// out of, divided by the units that production made.
//
// The money of the waste is never lost from the book: it leaves the
// inventory and it lands in the account of the waste, the account the book
// of the business opens for the product that never reached a client.
//
// The rotation of the output by the expiry is the rule that says which units
// leave, and the valuation of the stock by the FIFO is another rule: the
// model keeps the two apart.

// WasteID is the identity of a waste.
//
// The number is generated by the database. The type exists so that an
// identifier never travels as a plain integer by accident.
type WasteID int64

// WasteReason is the reason of a waste.
//
// The reason is what a later analysis reads: it is why the bakery lost what
// it lost. The reasons are the four of the book, and the book never guesses
// one of them.
type WasteReason string

const (
	// WasteBurnt is the waste of what the oven burnt.
	WasteBurnt WasteReason = "burnt"

	// WasteSpoiled is the waste of what spoiled.
	WasteSpoiled WasteReason = "spoiled"

	// WasteDropped is the waste of what fell, or what was dropped.
	WasteDropped WasteReason = "dropped"

	// WasteReturned is the waste of what came back.
	WasteReturned WasteReason = "returned"
)

// theReasonsOfTheWaste holds the reasons of the waste, in the order they
// are presented.
var theReasonsOfTheWaste = []WasteReason{
	WasteBurnt,
	WasteSpoiled,
	WasteDropped,
	WasteReturned,
}

// theSpokenReasons holds the names the owner and the agent say for the
// reasons of the waste.
//
// The names are read the way a person reads them, and the answer is the
// reason the book knows: the storage and the protocol carry the four names
// of the reasons.
var theSpokenReasons = map[string]WasteReason{
	"burnt":           WasteBurnt,
	"burned":          WasteBurnt,
	"quemado":         WasteBurnt,
	"quemada":         WasteBurnt,
	"spoiled":         WasteSpoiled,
	"echado a perder": WasteSpoiled,
	"podrido":         WasteSpoiled,
	"podrida":         WasteSpoiled,
	"dropped":         WasteDropped,
	"botado":          WasteDropped,
	"botada":          WasteDropped,
	"caido":           WasteDropped,
	"caída":           WasteDropped,
	"returned":        WasteReturned,
	"devuelto":        WasteReturned,
	"devuelta":        WasteReturned,
}

// AllWasteReasons returns the reasons of the waste, in the order they are
// presented.
//
// The vocabulary belongs to the domain: the description of the tool reads
// it, and the check of the table holds the same rule as a defense in
// depth.
func AllWasteReasons() []WasteReason {
	all := make([]WasteReason, len(theReasonsOfTheWaste))
	copy(all, theReasonsOfTheWaste)

	return all
}

// Valid reports whether the reason is one of the reasons of the book.
func (r WasteReason) Valid() bool {
	for _, one := range theReasonsOfTheWaste {
		if one == r {
			return true
		}
	}

	return false
}

// String returns the name of the reason.
//
// It is the name the storage and the protocol carry, with no translation in
// between.
func (r WasteReason) String() string {
	return string(r)
}

// ParseWasteReason answers the reason the owner named.
//
// The name is read the way a person reads it: trimmed, and without case.
// The answer is the reason the book knows, never the way it was said.
//
// The error is ErrUnknownWasteReason when the name is not one of the four
// reasons of the book: the reason is what a later analysis reads, and a
// reason nobody declared is never guessed.
func ParseWasteReason(spoken string) (WasteReason, error) {
	key := strings.ToLower(strings.TrimSpace(spoken))
	if key == "" {
		return "", fmt.Errorf("%w: the reason is not empty", ErrUnknownWasteReason)
	}

	reason, known := theSpokenReasons[key]
	if !known {
		return "", fmt.Errorf("%w: %q", ErrUnknownWasteReason, spoken)
	}

	return reason, nil
}

// WastedUnit is a unit of a production that the waste took out of the book.
//
// The unit carries the production it came out of: the money of the waste is
// the money of that production, and the analysis of the waste reads it from
// here.
type WastedUnit struct {
	// UnitID is the identity of the unit that left the book.
	UnitID UnitID

	// ProductionID is the production the unit came out of.
	ProductionID ProductionID

	// Position is the order the unit was made in.
	Position int

	// Grams is the weight of the unit.
	Grams float64

	// ExpiresOn is the day the unit expired on.
	ExpiresOn ledger.Date
}

// Waste is what the bakery lost.
//
// It carries the product, the quantity, the unit and the reason, and the
// money of what it was worth. The units that left the book travel with it:
// they are the units that expired first, and they are the ones a later
// analysis reads.
type Waste struct {
	// ID is the identity of the waste. It is empty until the storage
	// writes the row.
	ID WasteID

	// BusinessID is the business that owns the waste.
	BusinessID business.ID

	// RecipeID is the product the waste is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product. It is the
	// name of the recipe, and the recipe is the owner of it.
	RecipeName string

	// Day is the day the waste happened.
	Day ledger.Date

	// Quantity is how many units of the product the bakery lost.
	Quantity float64

	// Unit is the unit of that quantity: the waste of the bakery counts
	// the units it lost.
	Unit string

	// Reason is why the bakery lost them.
	Reason WasteReason

	// Money is the money of what was lost, in whole pesos: the cost the
	// waste releases.
	Money ledger.Amount

	// Units are the units of the production that left the book, in the
	// order they expire: the one that expires first is the first one.
	Units []WastedUnit

	// Utterance is the sentence of the owner, verbatim. It is empty when
	// she said none.
	Utterance string

	// ConfirmedWith is the word she used to confirm the waste.
	ConfirmedWith string

	// CreatedAt is the moment the row was created. The storage filled it.
	CreatedAt time.Time
}

// WasteDefinition is what the owner said about the waste.
//
// It is the candidate the agent read, and the domain decides what may enter
// the book of the business.
type WasteDefinition struct {
	// RecipeID is the product the waste is of. It is zero when the owner
	// names the product with its name.
	RecipeID ID

	// RecipeName is the name the owner reads of the product she lost. It
	// is empty when she names the product with its identity.
	RecipeName string

	// Quantity is how many units of the product the bakery lost.
	Quantity float64

	// Unit is the unit of that quantity. It is empty when the owner named
	// none, and the waste counts the units it lost.
	Unit string

	// Reason is why the bakery lost them.
	Reason WasteReason

	// Day is the day the waste happened.
	Day ledger.Date

	// Utterance is the sentence of the owner, verbatim. It is optional.
	Utterance string

	// ConfirmedWith is the word she used to confirm the waste.
	ConfirmedWith string
}

// WasteOf builds the waste the owner confirmed.
//
// The rules of the domain:
//
//   - the waste belongs to a business and names the product it lost: the
//     name of a product is not unique inside the business, and a name that
//     more than one product carries is refused, because the book never
//     guesses which product she lost;
//   - the quantity is positive and whole: the waste of the bakery counts
//     the units it lost, and the book never splits a unit;
//   - the unit is the unit of a piece: the book never converts a weight
//     into a number of units;
//   - the reason is one of the four of the book: the reason is what a
//     later analysis reads, and it is never guessed;
//   - the waste carries the day it happened and the word of the owner: the
//     waste is written with her confirmation, the way the production is
//     written;
//   - the units that leave the book are the units of the product that are
//     still in it, in the order they expire: the one that expires first is
//     the first one;
//   - the money of the waste is the money of the units that left: the money
//     of the production they came out of, divided by the units that
//     production made. The money of the book counts whole pesos.
func WasteOf(
	own business.ID,
	productions []Production,
	held []ExpiringUnit,
	definition WasteDefinition,
) (Waste, error) {
	if own <= 0 {
		return Waste{}, fmt.Errorf("%w: the waste is of the business %d",
			ErrMissingBusiness, own)
	}

	recipeID, err := theProductOfTheWaste(productions, definition)
	if err != nil {
		return Waste{}, err
	}

	if definition.Quantity <= 0 {
		return Waste{}, fmt.Errorf("%w: the waste carries %v units",
			ErrInvalidWasteQuantity, definition.Quantity)
	}

	if definition.Quantity != math.Trunc(definition.Quantity) {
		return Waste{}, fmt.Errorf("%w: the waste carries %v units",
			ErrInvalidWasteQuantity, definition.Quantity)
	}

	unit, err := theUnitOfTheWaste(definition.Unit)
	if err != nil {
		return Waste{}, err
	}

	if !definition.Reason.Valid() {
		return Waste{}, fmt.Errorf("%w: the reason of the waste is %q",
			ErrUnknownWasteReason, definition.Reason)
	}

	if definition.Day.Time().IsZero() {
		return Waste{}, fmt.Errorf("%w: the waste carries the day it happened",
			ErrMissingWasteDay)
	}

	word := strings.TrimSpace(definition.ConfirmedWith)
	if word == "" {
		return Waste{}, fmt.Errorf("%w: the waste carries the word of the owner",
			ErrMissingWasteConfirmation)
	}

	units := theUnitsOfTheProduct(held, recipeID)
	if len(units) < int(definition.Quantity) {
		return Waste{}, fmt.Errorf("%w: the book holds %d units of the product and the owner lost %v",
			ErrNotEnoughUnits, len(units), definition.Quantity)
	}

	taken := units[:int(definition.Quantity)]

	wasted := make([]WastedUnit, 0, len(taken))
	money := ledger.Amount(0)

	for _, one := range taken {
		price, err := theMoneyOfTheUnit(productions, one)
		if err != nil {
			return Waste{}, err
		}

		wasted = append(wasted, WastedUnit{
			UnitID:       one.ID,
			ProductionID: one.ProductionID,
			Position:     one.Position,
			Grams:        one.Grams,
			ExpiresOn:    one.ExpiresOn,
		})

		money += price
	}

	name := theNameOfTheProduct(productions, recipeID)

	return NewWaste(own, WasteFact{
		RecipeID:      recipeID,
		RecipeName:    name,
		Day:           definition.Day,
		Quantity:      definition.Quantity,
		Unit:          unit,
		Reason:        definition.Reason,
		Money:         money,
		Units:         wasted,
		Utterance:     definition.Utterance,
		ConfirmedWith: word,
	})
}

// WasteFact is what the book keeps of a waste.
//
// The fact carries what the owner said and what the book derived: the units
// that left the book and the money of what they were worth.
type WasteFact struct {
	// RecipeID is the product the waste is of.
	RecipeID ID

	// RecipeName is the name the owner reads of the product.
	RecipeName string

	// Day is the day the waste happened.
	Day ledger.Date

	// Quantity is how many units of the product the bakery lost.
	Quantity float64

	// Unit is the unit of that quantity.
	Unit string

	// Reason is why the bakery lost them.
	Reason WasteReason

	// Money is the money of what was lost, in whole pesos.
	Money ledger.Amount

	// Units are the units of the production that left the book.
	Units []WastedUnit

	// Utterance is the sentence of the owner, verbatim.
	Utterance string

	// ConfirmedWith is the word she used to confirm the waste.
	ConfirmedWith string
}

// NewWaste builds the waste of the business out of what the book keeps.
//
// The error is ErrMissingBusiness when the waste is of no business,
// ErrMissingRecipe when it names no product, ErrMissingWasteDay when it
// carries no day, ErrInvalidWasteQuantity when the quantity is not a whole
// number of units, ErrInvalidWasteUnit when the unit is not the unit of a
// piece, ErrUnknownWasteReason when the reason is not one of the four of
// the book, ErrNotEnoughUnits when the waste carries no unit, and
// ErrMissingWasteConfirmation when it carries no word of the owner.
func NewWaste(own business.ID, fact WasteFact) (Waste, error) {
	waste := Waste{
		BusinessID:    own,
		RecipeID:      fact.RecipeID,
		RecipeName:    strings.TrimSpace(fact.RecipeName),
		Day:           fact.Day,
		Quantity:      fact.Quantity,
		Unit:          strings.TrimSpace(fact.Unit),
		Reason:        fact.Reason,
		Money:         fact.Money,
		Units:         fact.Units,
		Utterance:     strings.TrimSpace(fact.Utterance),
		ConfirmedWith: strings.TrimSpace(fact.ConfirmedWith),
	}

	return waste.Checked()
}

// Checked answers the waste when it is whole, and the error when it is not.
//
// The rule of the domain: the waste belongs to a business, names the
// product it lost, carries a whole number of units with the unit of a piece,
// carries one of the four reasons, the day it happened and the word of the
// owner, and it carries the units that left the book.
//
// A row that another writer broke is refused, and it is never read as a
// waste.
func (w Waste) Checked() (Waste, error) {
	if w.BusinessID <= 0 {
		return Waste{}, fmt.Errorf("%w: the waste is of the business %d",
			ErrMissingBusiness, w.BusinessID)
	}

	if w.RecipeID <= 0 || strings.TrimSpace(w.RecipeName) == "" {
		return Waste{}, fmt.Errorf("%w: the waste names the product it lost",
			ErrMissingRecipe)
	}

	if w.Day.Time().IsZero() {
		return Waste{}, fmt.Errorf("%w: the waste carries the day it happened",
			ErrMissingWasteDay)
	}

	if w.Quantity <= 0 || w.Quantity != math.Trunc(w.Quantity) {
		return Waste{}, fmt.Errorf("%w: the waste carries %v units",
			ErrInvalidWasteQuantity, w.Quantity)
	}

	if w.Unit != ingredient.UnitPiece.String() {
		return Waste{}, fmt.Errorf("%w: the unit of the waste is %q",
			ErrInvalidWasteUnit, w.Unit)
	}

	if !w.Reason.Valid() {
		return Waste{}, fmt.Errorf("%w: the reason of the waste is %q",
			ErrUnknownWasteReason, w.Reason)
	}

	if w.Money < 0 {
		return Waste{}, fmt.Errorf("%w: the money of the waste is %d",
			ErrInvalidWasteMoney, w.Money)
	}

	if len(w.Units) == 0 {
		return Waste{}, fmt.Errorf("%w: the waste carries no unit",
			ErrNotEnoughUnits)
	}

	if strings.TrimSpace(w.ConfirmedWith) == "" {
		return Waste{}, fmt.Errorf("%w: the waste carries the word of the owner",
			ErrMissingWasteConfirmation)
	}

	return w, nil
}

// Movement answers the movement of the money of the waste.
//
// The money of the waste lands in the account of the waste and it comes from
// the inventory: the product never reached a client, and the money it was
// worth is not lost from the book - it is the expense the business carries.
//
// The description of the movement is the sentence of the owner when she said
// one, and the words of the book when she said none.
func (w Waste) Movement(waste, inventory account.ID) (ledger.Entry, error) {
	return ledger.NewEntry(w.BusinessID, waste, inventory, w.Money, w.Day, w.Description())
}

// Description answers what the person reads in the book.
//
// The rule of the domain: the sentence of the owner is what she reads, and
// the words of the book are what she reads when she said no sentence: the
// product, the number of units and the reason.
func (w Waste) Description() string {
	if utterance := strings.TrimSpace(w.Utterance); utterance != "" {
		return utterance
	}

	return fmt.Sprintf("Merma: %v unidades de %s (%s)", w.Quantity, w.RecipeName, w.Reason)
}

// theProductOfTheWaste answers the product the waste is of.
//
// The rule of the domain: the identity of a product answers that product
// alone, and the name the owner reads answers the products that carry it:
// the name of a product is not unique inside the business, and a name that
// more than one product carries is refused, because the book never guesses
// which product she lost.
//
// The error is ErrMissingRecipe when the waste names no product,
// ErrUnknownRecipe when the business holds no product with that name, and
// ErrAmbiguousRecipe when it holds more than one.
func theProductOfTheWaste(productions []Production, definition WasteDefinition) (ID, error) {
	return theProductOfTheBook(productions, definition.RecipeID, definition.RecipeName, "waste")
}

// theProductOfTheBook answers the product an exit of the book is of.
//
// The rule of the domain: the identity of a product answers that product
// alone, and the name the owner reads answers the products that carry it:
// the name of a product is not unique inside the business, and a name that
// more than one product carries is refused, because the book never guesses
// which product she lost or sold.
//
// The subject names what the exit is, so the refusal says what the owner
// has to tell.
//
// The error is ErrMissingRecipe when the exit names no product,
// ErrUnknownRecipe when the business holds no product with that name, and
// ErrAmbiguousRecipe when it holds more than one.
func theProductOfTheBook(productions []Production, id ID, name, subject string) (ID, error) {
	if id > 0 {
		for _, one := range productions {
			if one.RecipeID == id {
				return one.RecipeID, nil
			}
		}

		return 0, fmt.Errorf("%w: the product %d", ErrUnknownRecipe, id)
	}

	spoken := strings.TrimSpace(name)
	if spoken == "" {
		return 0, fmt.Errorf("%w: the %s names no product", ErrMissingRecipe, subject)
	}

	found := make([]ID, 0)

	for _, one := range productions {
		if !strings.EqualFold(strings.TrimSpace(one.RecipeName), strings.TrimSpace(spoken)) {
			continue
		}

		if !holdsTheProduct(found, one.RecipeID) {
			found = append(found, one.RecipeID)
		}
	}

	switch len(found) {
	case 0:
		return 0, fmt.Errorf("%w: the business holds no product named %q", ErrUnknownRecipe, spoken)
	case 1:
		return found[0], nil
	default:
		return 0, fmt.Errorf("%w: the business holds %d products named %q",
			ErrAmbiguousRecipe, len(found), spoken)
	}
}

// holdsTheProduct reports whether the list already carries the product.
func holdsTheProduct(found []ID, of ID) bool {
	for _, one := range found {
		if one == of {
			return true
		}
	}

	return false
}

// theNameOfTheProduct answers the name the owner reads of the product.
//
// The rule of the domain: the name of the product is the name of the recipe
// it was made of, and the waste never becomes a second truth about it.
func theNameOfTheProduct(productions []Production, of ID) string {
	for _, one := range productions {
		if one.RecipeID == of {
			return one.RecipeName
		}
	}

	return ""
}

// theUnitOfTheWaste answers the unit of the quantity of the waste.
//
// The rule of the domain: the waste of the bakery counts the units it lost,
// and the unit of a piece is the one the book knows. The unit is empty when
// the owner named none, and the waste counts the units it lost then.
//
// The error is ErrInvalidWasteUnit when the unit is another one: the book
// never converts a weight into a number of units, and it never splits a
// unit.
func theUnitOfTheWaste(unit string) (string, error) {
	return theUnitOfTheBook(unit, ErrInvalidWasteUnit)
}

// theUnitOfTheBook answers the unit of the quantity of an exit of the book.
//
// The rule of the domain: the exits of the bakery count the units they
// took, and the unit of a piece is the one the book knows. The unit is
// empty when the owner named none, and the exit counts the units it took
// then.
//
// The error is the one the caller names when the unit is another one: the
// book never converts a weight into a number of units, and it never splits
// a unit.
func theUnitOfTheBook(unit string, invalid error) (string, error) {
	if strings.TrimSpace(unit) == "" {
		return ingredient.UnitPiece.String(), nil
	}

	parsed, err := ingredient.ParseUnit(unit)
	if err != nil {
		return "", fmt.Errorf("%w: the unit is %q", invalid, unit)
	}

	if parsed != ingredient.UnitPiece {
		return "", fmt.Errorf("%w: the unit is %q", invalid, parsed.String())
	}

	return parsed.String(), nil
}

// theMoneyOfTheUnit answers the money of one unit of a production.
//
// The rule of the domain: the money of a unit is the money of the
// production it came out of, divided by the units that production made. The
// money of the book counts whole pesos, and the answer is rounded to the
// nearest peso.
//
// The remainder stays in the inventory: the rounding of the money of a unit
// may release one peso more or one peso less than the money of the
// production it came out of, and the difference is never lost from the
// book - it stays in the inventory of the business.
//
// The error is ErrUnknownProduction when the production of the unit is not
// there: the money of a unit is the money of the production it came out of,
// and the book never guesses it.
func theMoneyOfTheUnit(productions []Production, unit ExpiringUnit) (ledger.Amount, error) {
	for _, one := range productions {
		if one.ID != unit.ProductionID {
			continue
		}

		if len(one.Units) == 0 {
			return 0, fmt.Errorf("%w: the production %d made no unit",
				ErrMissingProductionUnits, one.ID)
		}

		share := float64(one.Money) / float64(len(one.Units))

		return ledger.Amount(math.Round(share)), nil
	}

	return 0, fmt.Errorf("%w: the production %d of the unit %d",
		ErrUnknownProduction, unit.ProductionID, unit.ID)
}
